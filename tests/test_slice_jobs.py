# Same line G6 ignores. Two real slices of one input differ only here.
STAMP = re.compile(rb"^; generated by OrcaSlicer \S+ on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}\r?$")
PROFILE = "apex-v2-insole-95a"


def without_stamp(body: bytes) -> bytes:
    lines = body.split(b"\n")
    hits = [i for i, line in enumerate(lines) if STAMP.match(line)]
    if len(hits) > 1:
        raise AssertionError(f"more than one Orca timestamp line ({len(hits)})")
    return b"\n".join(line for i, line in enumerate(lines) if i not in hits)


def _gcode_file(work_dir, payload: bytes) -> Path:
    work = Path(work_dir)
    work.mkdir(parents=True, exist_ok=True)
    path = work / "out.gcode"
    path.write_bytes(payload)
    return path


def _stats():
    return {"elapsed_s": 1.25, "peak_rss_kb": 42, "chain": "apex_core-g2b-v1"}


