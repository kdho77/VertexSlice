    async def _health_during_slice(self):
        import httpx

        hold = self._hold()
        started = threading.Event()

        def fake(dest, profile, **kwargs):
            started.set()
            self.assertTrue(hold.wait(10))
            return _gcode_file(kwargs["work_dir"], b"; health\n"), _stats()

        with mock.patch("server.app.slice_stl", fake):
            transport = httpx.ASGITransport(app=self.app)
            async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
                task = asyncio.create_task(
                    client.post(
                        "/v1/slice",
                        data={"profile_id": PROFILE, "material": "apex_core"},
                        files={"model": ("m.stl", b"solid h\nendsolid h\n", "model/stl")},
                    )
                )
                try:
                    deadline = time.monotonic() + 5
                    while not started.is_set() and time.monotonic() < deadline:
                        await asyncio.sleep(0.02)
                    self.assertTrue(started.is_set(), "sync slice did not start")
                    samples = []
                    for _ in range(10):
                        t0 = time.perf_counter()
                        health = await client.get("/health")
                        samples.append(time.perf_counter() - t0)
                        self.assertEqual(health.status_code, 200)
                        self.assertEqual(health.json()["status"], "ok")
                    hold.set()
                    response = await asyncio.wait_for(task, timeout=10)
                finally:
                    hold.set()
                    if not task.done():
                        task.cancel()
        self.assertEqual(response.status_code, 200, response.text)
        self.assertEqual(response.content, b"; health\n")
        worst = max(samples)
        self.assertLess(worst, 1.0, f"GET /health took {worst:.3f}s during a slice")
        print(f"HEALTH_DURING_SLICE_MAX_S={worst:.4f}")

    def test_sync_disconnect_kills_subprocess_and_frees_worker(self):
        asyncio.run(self._disconnect())

    async def _disconnect(self):
        import httpx

        procs: list[subprocess.Popen] = []
        state = {"n": 0}

        def fake(dest, profile, **kwargs):
            state["n"] += 1
            if state["n"] == 1:
                proc = subprocess.Popen([sys.executable, "-c", "import time; time.sleep(60)"])
                procs.append(proc)
                try:
                    proc.wait(timeout=8)
                except subprocess.TimeoutExpired:
                    proc.kill()
                    proc.wait(timeout=2)
                    raise RuntimeError("subprocess was not killed on disconnect") from None
                raise RuntimeError(f"slice subprocess exited {proc.returncode}")
            return _gcode_file(kwargs["work_dir"], b"; next\n"), _stats()

        with mock.patch("server.app.slice_stl", fake):
            transport = httpx.ASGITransport(app=self.app)
            async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
                task = asyncio.create_task(
                    client.post(
                        "/v1/slice",
                        data={"profile_id": PROFILE, "material": "apex_core"},
                        files={"model": ("m.stl", b"solid d\nendsolid d\n", "model/stl")},
                    )
                )
                deadline = time.monotonic() + 5
                while not procs and time.monotonic() < deadline:
                    await asyncio.sleep(0.02)
                self.assertTrue(procs, "sync slice did not start a subprocess")
                task.cancel()
                with self.assertRaises(asyncio.CancelledError):
                    await task
                dead = time.monotonic() + 2
                while procs[0].poll() is None and time.monotonic() < dead:
                    await asyncio.sleep(0.02)
                self.assertIsNotNone(procs[0].poll(), "disconnect left the slice subprocess running")
                follow = await asyncio.wait_for(
                    client.post(
                        "/v1/slice",
                        data={"profile_id": PROFILE, "material": "apex_core"},
                        files={"model": ("m.stl", b"solid d\nendsolid d\n", "model/stl")},
                    ),
                    timeout=10,
                )
        self.assertEqual(follow.status_code, 200, follow.text)
        self.assertEqual(follow.content, b"; next\n")

    def test_disconnect_poll_kills_the_running_slice(self):
        asyncio.run(self._disconnect_poll())

    async def _disconnect_poll(self):
        from server.app import _await_slice
        from server.jobs import PreparedSlice

        proc_box: list[subprocess.Popen] = []
        started = threading.Event()

        def fake(dest, profile, **kwargs):
            proc = subprocess.Popen([sys.executable, "-c", "import time; time.sleep(60)"])
            proc_box.append(proc)
            started.set()
            try:
                proc.wait(timeout=8)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait(timeout=2)
                raise RuntimeError("subprocess was not killed on disconnect") from None
            raise RuntimeError(f"slice subprocess exited {proc.returncode}")

        class Drop:
            def __init__(self):
                self.gone = False

            async def is_disconnected(self):
                return self.gone

        prepared = PreparedSlice(
            model_bytes=b"solid d\nendsolid d\n",
            suffix=".stl",
            filename="m.stl",
            profile_id=PROFILE,
            material_id="apex_core",
            profile=object(),
            overrides={},
            belt_insole_place=True,
            timeout_s=260,
        )
        request = Drop()
        with mock.patch("server.app.slice_stl", fake):
            item = self.queue.submit_sync(prepared)
            waiter = asyncio.create_task(_await_slice(item, request))
            self.assertTrue(started.wait(5))
            request.gone = True
            outcome = await asyncio.wait_for(waiter, timeout=8)
        self.assertEqual(outcome, "cancelled")
        self.assertIsNotNone(proc_box[0].poll())
        self.assertNotEqual(proc_box[0].returncode, 0)


