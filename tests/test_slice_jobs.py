    def test_kill_new_descendants_leaves_older_processes(self):
        from server.jobs import descendant_pids, kill_new_descendants

        old = subprocess.Popen([sys.executable, "-c", "import time; time.sleep(30)"])
        new = None
        try:
            before = set(descendant_pids(os.getpid()))
            self.assertIn(old.pid, before)
            new = subprocess.Popen([sys.executable, "-c", "import time; time.sleep(30)"])
            kill_new_descendants(os.getpid(), before)
            new.wait(timeout=2)
            self.assertIsNone(old.poll())
            self.assertNotEqual(new.returncode, 0)
        finally:
            if new is not None and new.poll() is None:
                new.kill()
                new.wait(timeout=2)
            if old.poll() is None:
                old.kill()
                old.wait(timeout=2)

