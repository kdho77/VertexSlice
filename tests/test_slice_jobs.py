    def test_unknown_job_is_404_and_unfinished_result_is_409(self):
        from fastapi.testclient import TestClient

        hold = self._hold()
        started = threading.Event()

        def fake(dest, profile, **kwargs):
            started.set()
            self.assertTrue(hold.wait(10))
            return _gcode_file(kwargs["work_dir"], b"; held\n"), _stats()

        with mock.patch("server.app.slice_stl", fake):
            client = TestClient(self.app)
            missing = client.get("/v1/slice/jobs/does-not-exist")
            self.assertEqual(missing.status_code, 404)
            missing_result = client.get("/v1/slice/jobs/does-not-exist/result")
            self.assertEqual(missing_result.status_code, 404)
            accepted = self._post_job(client, b"solid held\nendsolid held\n")
            self.assertEqual(accepted.status_code, 202)
            self.assertEqual(accepted.json()["status"], "queued")
            job_id = accepted.json()["job_id"]
            self.assertTrue(started.wait(5))
            status = client.get(f"/v1/slice/jobs/{job_id}")
            self.assertEqual(status.status_code, 200)
            self.assertEqual(status.json()["status"], "running")
            self.assertIsNone(status.json()["position"])
            early = client.get(f"/v1/slice/jobs/{job_id}/result")
            self.assertEqual(early.status_code, 409)
            hold.set()
            deadline = time.monotonic() + 5
            body = status.json()
            while time.monotonic() < deadline and body["status"] != "succeeded":
                body = client.get(f"/v1/slice/jobs/{job_id}").json()
                time.sleep(0.02)
            self.assertEqual(body["status"], "succeeded")
            # Still stored under the default retention. Expiring is a separate threshold.
            self.assertIsNotNone(self.queue.get(job_id))
            self.queue.retention_s = 0
            self.assertIsNone(self.queue.get(job_id))
            expired = client.get(f"/v1/slice/jobs/{job_id}")
            self.assertEqual(expired.status_code, 404)
            expired_result = client.get(f"/v1/slice/jobs/{job_id}/result")
            self.assertEqual(expired_result.status_code, 404)

