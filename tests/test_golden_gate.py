"""Synthetic tests for scripts/golden_gate.py (no committed G-code fixtures)."""
from __future__ import annotations

import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scripts"))

import golden_gate  # noqa: E402

compare_paths = golden_gate.compare_paths
normalize_gcode_text = golden_gate.normalize_gcode_text


class GoldenGateNormalizeTest(unittest.TestCase):
    def _write_pair(self, left: str, right: str) -> tuple[Path, Path]:
        tmp = Path(tempfile.mkdtemp())
        left_path = tmp / "left.gcode"
        right_path = tmp / "right.gcode"
        left_path.write_text(left, encoding="utf-8")
        right_path.write_text(right, encoding="utf-8")
        return left_path, right_path

    def test_timestamp_only_diff_passes(self):
        left = (
            "; generated by OrcaSlicer 2.3.2-dev on 2026-10-31 at 12:00:00\n"
            "G1 F1200 X1 Y1\n"
        )
        right = (
            "; generated by OrcaSlicer 2.3.2-dev on 2026-10-31 at 99:99:99\n"
            "G1 F1200 X1 Y1\n"
        )
        lp, rp = self._write_pair(left, right)
        result = compare_paths(lp, rp)
        self.assertTrue(result.ok, result.diffs)
        self.assertEqual(result.left_sha256, result.right_sha256)

    def test_object_name_diff_passes(self):
        body = "G1 F1200 X1 Y1\n"
        left = "; printing object insole_left id:42 copy 1\n" + body
        right = "; printing object insole_right id:42 copy 1\n" + body
        lp, rp = self._write_pair(left, right)
        result = compare_paths(lp, rp)
        self.assertTrue(result.ok)
        self.assertEqual(
            normalize_gcode_text(left),
            ["; printing object <OBJ>", "G1 F1200 X1 Y1"],
        )

    def test_stop_printing_object_normalized(self):
        left = "; stop printing object foo id:1 copy 0\nG1 X0\n"
        right = "; stop printing object bar id:99 copy 3\nG1 X0\n"
        lp, rp = self._write_pair(left, right)
        self.assertTrue(compare_paths(lp, rp).ok)

    def test_crlf_vs_lf_passes(self):
        left = "G1 X1\r\nG1 Y1\r\n"
        right = "G1 X1\nG1 Y1\n"
        lp, rp = self._write_pair(left, right)
        self.assertTrue(compare_paths(lp, rp).ok)

    def test_feedrate_diff_fails(self):
        left = "G1 F1200 X1 Y1\n"
        right = "G1 F2400 X1 Y1\n"
        lp, rp = self._write_pair(left, right)
        result = compare_paths(lp, rp)
        self.assertFalse(result.ok)
        self.assertEqual(result.diff_count, 1)
        self.assertIn("F1200", result.diffs[0].left or "")
        self.assertIn("F2400", result.diffs[0].right or "")

    def test_slow_down_layer_time_diff_fails(self):
        left = "; slow_down_layer_time = 8\nG1 X0\n"
        right = "; slow_down_layer_time = 4\nG1 X0\n"
        lp, rp = self._write_pair(left, right)
        result = compare_paths(lp, rp)
        self.assertFalse(result.ok)
        self.assertEqual(result.diff_count, 1)


if __name__ == "__main__":
    unittest.main()
