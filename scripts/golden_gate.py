#!/usr/bin/env python3
"""Normalized G-code golden gate: compare two files ignoring timestamp and object-name comments."""
from __future__ import annotations

import hashlib
import re
import sys
from dataclasses import dataclass
from pathlib import Path

_GENERATED_BY = re.compile(r"^; generated by ")
_OBJECT_COMMENT = re.compile(r"^; (stop )?printing object .* id:\d+ copy \d+$")


def normalize_line(line: str) -> str | None:
    """Return normalized line content, or None if the line is dropped."""
    if _GENERATED_BY.match(line):
        return None
    m = _OBJECT_COMMENT.match(line)
    if m:
        stop = m.group(1) or ""
        return f"; {stop}printing object <OBJ>"
    return line


def normalize_gcode_text(text: str) -> list[str]:
    """Split *text* into lines (CRLF/LF agnostic) and apply golden-gate normalization."""
    out: list[str] = []
    for line in text.splitlines():
        norm = normalize_line(line)
        if norm is not None:
            out.append(norm)
    return out


def normalized_sha256(lines: list[str]) -> str:
    payload = "\n".join(lines)
    if lines:
        payload += "\n"
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class LineDiff:
    index: int
    left: str | None
    right: str | None


@dataclass(frozen=True)
class CompareResult:
    left_sha256: str
    right_sha256: str
    diff_count: int
    diffs: list[LineDiff]

    @property
    def ok(self) -> bool:
        return self.diff_count == 0


def compare_normalized(left_lines: list[str], right_lines: list[str]) -> CompareResult:
    max_len = max(len(left_lines), len(right_lines))
    diffs: list[LineDiff] = []
    for i in range(max_len):
        a = left_lines[i] if i < len(left_lines) else None
        b = right_lines[i] if i < len(right_lines) else None
        if a != b:
            diffs.append(LineDiff(index=i + 1, left=a, right=b))
    return CompareResult(
        left_sha256=normalized_sha256(left_lines),
        right_sha256=normalized_sha256(right_lines),
        diff_count=len(diffs),
        diffs=diffs,
    )


def read_gcode(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="surrogateescape")


def compare_paths(left: Path, right: Path) -> CompareResult:
    left_lines = normalize_gcode_text(read_gcode(left))
    right_lines = normalize_gcode_text(read_gcode(right))
    return compare_normalized(left_lines, right_lines)


def format_report(result: CompareResult, *, max_diffs: int = 20) -> str:
    lines = [
        f"normalized_sha256_left={result.left_sha256}",
        f"normalized_sha256_right={result.right_sha256}",
        f"diff_count={result.diff_count}",
    ]
    for diff in result.diffs[:max_diffs]:
        lines.append(f"diff line {diff.index}: left={diff.left!r} right={diff.right!r}")
    if result.diff_count > max_diffs:
        lines.append(f"... {result.diff_count - max_diffs} more diff(s) omitted")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) != 2 or args[0] in ("-h", "--help"):
        print(
            "usage: python3 scripts/golden_gate.py LEFT.gcode RIGHT.gcode",
            file=sys.stderr,
        )
        print(
            "  Compare normalized G-code (ignores ; generated by … and object id/copy comments).",
            file=sys.stderr,
        )
        return 2 if len(args) != 2 else 0

    left = Path(args[0])
    right = Path(args[1])
    result = compare_paths(left, right)
    print(format_report(result))
    return 0 if result.ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
