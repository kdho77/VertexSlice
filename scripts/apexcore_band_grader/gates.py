ALLOWED_FILES = (
    "scripts/g2b_heelmod/postprocess_g2b.py",
    "scripts/g2b_heelmod/test_seam_fuse.py",
)
BAND_LO = 156
BAND_HI = 165
FOREFOOT_LAST = 165
WALL_CLEARANCE_MM = 0.2
TRAVEL_EMPTY_MM = 2.0
THROUGH_WALL_MM = 0.2
E_RATIO_MIN_LEN = 0.2
SEAM_EDGE_MM = 1.0


def _result(gate: str, passed: bool, threshold: str, measured: dict, command: str) -> dict:
    return {
        "gate": gate,
        "pass": bool(passed),
        "threshold": threshold,
        "measured": measured,
        "command": command,
    }


def git_name_only(repo: str, base: str, head: str) -> list[str]:
    out = subprocess.check_output(
        ["git", "diff", "--name-only", f"{base}..{head}"],
        cwd=repo,
        text=True,
    )
    return [line for line in out.splitlines() if line.strip()]


def git_numstat(repo: str, base: str, head: str) -> list[dict]:
    out = subprocess.check_output(
        ["git", "diff", "--numstat", f"{base}..{head}"],
        cwd=repo,
        text=True,
    )
    rows = []
    for line in out.splitlines():
        if not line.strip():
            continue
        added, deleted, path = line.split("\t", 2)
        rows.append({"path": path, "insertions": int(added), "deletions": int(deleted)})
    return rows


def gate_g1(files: list[str], command: str, numstat: list[dict] | None = None) -> dict:
    extra = sorted(set(files) - set(ALLOWED_FILES))
    return _result(
        "G1",
        not extra,
        "git diff touches only scripts/g2b_heelmod/postprocess_g2b.py and scripts/g2b_heelmod/test_seam_fuse.py",
        {"files": files, "extra_files": extra, "numstat": numstat or []},
        command,
    )


def gate_g2(base_lines: list[str], cand_lines: list[str], command: str) -> dict:
    diffs = stamp_diffs(base_lines, cand_lines)
    others = [row for row in diffs if row["kind"] != "stamp"]
    return _result(
        "G2",
        not others,
        "insole2 identical except '; generated by OrcaSlicer ... at <time>' comment lines",
        {
            "diff_count": len(diffs),
            "non_stamp_diffs": others[:20],
            "stamp_diffs": [row for row in diffs if row["kind"] == "stamp"],
        },
        command,
    )


def gate_g3(base_layers: list[Layer], cand_layers: list[Layer], base_pre: list[str], cand_pre: list[str], command: str) -> dict:
    if len(base_layers) != len(cand_layers):
        return _result(
            "G3",
            False,
            f"differing layers only inside {BAND_LO}-{BAND_HI} inclusive (0-based ;LAYER_CHANGE index)",
            {"base_layers": len(base_layers), "cand_layers": len(cand_layers), "differing_layers": []},
            command,
        )
    differing = [layer.index for layer, other in zip(base_layers, cand_layers) if layer.lines != other.lines]
    outside = [index for index in differing if index < BAND_LO or index > BAND_HI]
    pre_diffs = stamp_diffs(base_pre, cand_pre)
    pre_other = [row for row in pre_diffs if row["kind"] != "stamp"]
    passed = not outside and not pre_other
    return _result(
        "G3",
        passed,
        f"differing layers only inside {BAND_LO}-{BAND_HI} inclusive; preamble may change only the slicer timestamp",
        {
            "differing_layers": differing,
            "outside_band": outside,
            "preamble_non_stamp": pre_other[:10],
            "preamble_stamp": [row for row in pre_diffs if row["kind"] == "stamp"],
        },
        command,
    )


def _classify_added(layer: Layer, added_indexes: set[int]) -> Counter:
    counts: Counter = Counter()
    typ = "?"
    for index, line in enumerate(layer.lines):
        stripped = line.strip()
        if stripped.startswith(";TYPE:"):
            if index in added_indexes:
                counts["comment_type"] += 1
            typ = stripped[6:].strip()
            continue
        if index not in added_indexes:
            continue
        if stripped.startswith(";WIDTH:"):
            counts["comment_width"] += 1
            continue
        if stripped.startswith(";"):
            counts["comment_other"] += 1
            continue
        if not stripped.startswith(("G0", "G1")):
            counts["other"] += 1
            continue
        body = stripped.split(";", 1)[0]
        has_x = "X" in body or "Y" in body
        has_e = "E" in body.split("F")[0] or any(tok.startswith("E") for tok in body.split())
        e_tok = next((tok for tok in body.split() if tok.startswith("E")), None)
        e_val = None
        if e_tok:
            try:
                e_val = float(e_tok[1:])
            except ValueError:
                e_val = None
        xy = has_x and any(tok[:1] in "XY" for tok in body.split())
        if e_val is not None and e_val < 0 and not xy:
            counts["retract"] += 1
        elif e_val is not None and e_val > 0 and not xy:
            counts["prime"] += 1
        elif xy and e_val is not None and e_val > 0:
            key = "extrude_sparse" if typ == "Sparse infill" else "extrude_other"
            counts[key] += 1
            counts[f"extrude_type:{typ}"] += 1
        elif xy:
            counts["travel"] += 1
        elif "F" in body:
            counts["feed_only"] += 1
        else:
            counts["other"] += 1
    return counts


def gate_g4(base_layers: list[Layer], cand_layers: list[Layer], command: str) -> dict:
    per_layer = []
    removed_total = 0
    modified_examples = []
    for base, cand in zip(base_layers, cand_layers):
        if base.lines == cand.lines:
            continue
        ok, added, missing = line_delta(base.lines, cand.lines)
        counts = _classify_added(cand, set(added)) if ok else Counter()
        removed_total += len(missing)
        if missing and len(modified_examples) < 8:
            modified_examples.append(
                {
                    "layer": base.index,
                    "missing_line_indexes": missing[:8],
                    "sample": [base.lines[i].strip()[:160] for i in missing[:3]],
                }
            )
        per_layer.append(
            {
                "layer": base.index,
                "baseline_is_subsequence": ok,
                "added_lines": len(added),
                "removed_or_modified_baseline_lines": len(missing),
                "counts": dict(counts),
            }
        )
    extrude_other = sum(row["counts"].get("extrude_other", 0) for row in per_layer)
    passed = removed_total == 0 and all(row["baseline_is_subsequence"] for row in per_layer) and extrude_other == 0
    # A layer that fails the subsequence has no counts; still a fail via removed_total / ok flag.
    if any(not row["baseline_is_subsequence"] for row in per_layer):
        passed = False
    return _result(
        "G4",
        passed,
        "inside differing layers every baseline line remains in order; only lines are added; added extrusions are sparse infill",
        {
            "layers": per_layer,
            "removed_or_modified_baseline_lines": removed_total,
            "added_extrude_other": extrude_other,
            "examples": modified_examples,
        },
        command,
    )


def _surface_signature(layer: Layer, types: set[str]) -> list[tuple]:
    rows = []
    for seg in layer.segments:
        if seg.kind == "extrude" and seg.typ in types:
            rows.append((seg.x0, seg.y0, seg.x1, seg.y1, seg.e, seg.width))
    return rows


def gate_g5(base_layers: list[Layer], cand_layers: list[Layer], command: str) -> dict:
    mismatches = []
    base_count = cand_count = 0
    for base, cand in zip(base_layers, cand_layers):
        left = _surface_signature(base, SHELL)
        right = _surface_signature(cand, SHELL)
        base_count += len(left)
        cand_count += len(right)
        if left != right and len(mismatches) < 10:
            mismatches.append({"layer": base.index, "base_moves": len(left), "cand_moves": len(right)})
    passed = not mismatches and len(base_layers) == len(cand_layers)
    return _result(
        "G5",
        passed,
        "Outer wall and Overhang wall extrusions match in count, coordinates, extrusion, and width on every layer",
        {
            "baseline_moves": base_count,
            "candidate_moves": cand_count,
            "mismatched_layers": mismatches,
        },
        command,
    )


def _seam_record(layer: Layer) -> dict:
    return {
        "z": layer.z,
        "travels": [(mark.typ, mark.x, mark.y, mark.z) for mark in layer.seams if mark.kind == "travel"],
        "starts": [(mark.typ, mark.x, mark.y) for mark in layer.seams if mark.kind == "start"],
    }


def _classify_seam(layer: Layer, y: float) -> str:
    ys = [seg.y0 for seg in layer.segments if seg.kind == "extrude" and seg.typ == "Outer wall"]
    ys += [seg.y1 for seg in layer.segments if seg.kind == "extrude" and seg.typ == "Outer wall"]
    if not ys:
        return "unknown"
    low, high = min(ys), max(ys)
    if y <= low + SEAM_EDGE_MM:
        return "bottom"
    if y >= high - SEAM_EDGE_MM:
        return "top"
    return "side"


def gate_g6(base_layers: list[Layer], cand_layers: list[Layer], command: str) -> dict:
    moved = []
    moved_count = 0
    class_counts = Counter()
    preexisting = []
    newly_top_or_side = []
    for base, cand in zip(base_layers, cand_layers):
        if _seam_record(base) != _seam_record(cand):
            moved_count += 1
            if len(moved) < 8:
                moved.append({"layer": base.index, "base": _seam_record(base), "cand": _seam_record(cand)})
        base_starts = {(mark.typ, mark.x, mark.y) for mark in base.seams if mark.kind == "start" and mark.typ in SHELL}
        for mark in cand.seams:
            if mark.kind != "start" or mark.typ not in SHELL:
                continue
            label = _classify_seam(cand, mark.y)
            class_counts[label] += 1
            if label not in ("top", "side"):
                continue
            row = {"layer": cand.index, "typ": mark.typ, "x": mark.x, "y": mark.y, "class": label}
            if (mark.typ, mark.x, mark.y) in base_starts:
                if len(preexisting) < 8:
                    preexisting.append(row)
            elif len(newly_top_or_side) < 8:
                newly_top_or_side.append(row)
    passed = not moved and not newly_top_or_side and len(base_layers) == len(cand_layers)
    return _result(
        "G6",
        passed,
        "layer-change Z and seam travel/start coordinates identical to baseline; no shell seam start moved onto the top or the side (bottom = within 1 mm of min outer-wall Y)",
        {
            "moved_layer_count": moved_count,
            "moved_layers": moved,
            "seam_start_classes": dict(class_counts),
            "preexisting_top_or_side": preexisting,
            "newly_top_or_side": newly_top_or_side,
        },
        command,
    )


def _added_indexes(base: Layer, cand: Layer) -> set[int]:
    if base.lines == cand.lines:
        return set()
    _ok, added, _missing = line_delta(base.lines, cand.lines)
    return set(added)


def _added_extrusions(base: Layer, cand: Layer) -> list:
    added_set = _added_indexes(base, cand)
    return [seg for seg in cand.segments if seg.kind == "extrude" and seg.line_no in added_set]


def _added_segments(base: Layer, cand: Layer) -> list:
    added_set = _added_indexes(base, cand)
    return [seg for seg in cand.segments if seg.line_no in added_set]


def gate_g7(base_layers: list[Layer], cand_layers: list[Layer], command: str) -> dict:
    closest = None
    violations = []
    checked = 0
    for base, cand in zip(base_layers, cand_layers):
        added = _added_extrusions(base, cand)
        added_ids = {seg.line_no for seg in added}
        walls = [seg for seg in cand.segments if seg.kind == "extrude" and seg.typ in SHELL and seg.line_no not in added_ids]
        for seg in added:
            checked += 1
            best = None
            crossed = False
            for wall in walls:
                if segments_properly_cross(seg, wall):
                    crossed = True
                    dist = 0.0
                else:
                    dist = segment_distance(seg, wall)
                if best is None or dist < best:
                    best = dist
            if best is None:
                continue
            if closest is None or best < closest:
                closest = best
            if crossed or best <= WALL_CLEARANCE_MM:
                if len(violations) < 12:
                    violations.append(
                        {
                            "layer": cand.index,
                            "distance_mm": best,
                            "crossed": crossed,
                            "x0": seg.x0,
                            "y0": seg.y0,
                            "x1": seg.x1,
                            "y1": seg.y1,
                            "type": seg.typ,
                        }
                    )
    passed = not violations
    return _result(
        "G7",
        passed,
        f"no added extrusion within {WALL_CLEARANCE_MM} mm of, or crossing, an outer-wall or overhang-wall path",
        {
            "added_extrusions_checked": checked,
            "min_distance_mm": closest,
            "violations": violations,
        },
        command,
    )


def _extrusion_cross_signature(layer: Layer, x: float) -> list[tuple]:
    rows = []
    for seg in layer.segments:
        if seg.kind != "extrude":
            continue
        dx = seg.x1 - seg.x0
        if abs(dx) < 1e-9:
            continue
        if min(seg.x0, seg.x1) <= x <= max(seg.x0, seg.x1):
            t = (x - seg.x0) / dx
            y = seg.y0 + t * (seg.y1 - seg.y0)
            rows.append((seg.typ, round(y, 3), round(seg.width, 3)))
    return sorted(rows)


def gate_g8(base_layers: list[Layer], cand_layers: list[Layer], command: str) -> dict:
    thicknesses = []
    outside = []
    thin_mismatch = []
    samples = 0
    for base, cand in zip(base_layers, cand_layers):
        for seg in _added_extrusions(base, cand):
            for x, y in sample_segment(seg, 0.25):
                samples += 1
                thick = thickness_at_point(cand.segments, x, y)
                if thick is None:
                    if len(outside) < 12:
                        outside.append({"layer": cand.index, "x": x, "y": y, "type": seg.typ})
                    continue
                thicknesses.append(thick)
                if thick < THICK_MIN_MM and len(outside) < 12:
                    outside.append({"layer": cand.index, "x": x, "y": y, "thickness_mm": thick, "type": seg.typ})
        if base.lines == cand.lines:
            continue
        xs = [coord for seg in base.segments if seg.kind == "extrude" for coord in (seg.x0, seg.x1)]
        if not xs:
            continue
        x = math.floor(min(xs))
        limit = max(xs)
        while x <= limit:
            thick = part_thickness(base.segments, x + 0.0)
            if thick is not None and thick < THICK_MIN_MM:
                if _extrusion_cross_signature(base, x) != _extrusion_cross_signature(cand, x):
                    if len(thin_mismatch) < 12:
                        thin_mismatch.append({"layer": base.index, "x": x, "thickness_mm": round(thick, 3)})
            x += 0.5
    under = [value for value in thicknesses if value < THICK_MIN_MM]
    min_thick = min(thicknesses) if thicknesses else None
    passed = not outside and not thin_mismatch and not under
    return _result(
        "G8",
        passed,
        "added extrusions lie in a shell section of thickness >= 3.0 mm; X stations under 3.0 mm in a differing layer keep the baseline extrusions",
        {
            "samples": samples,
            "min_thickness_mm": None if min_thick is None else round(min_thick, 4),
            "samples_under_3mm": len(under),
            "outside_shell_or_thin": outside,
            "thin_station_mismatches": thin_mismatch,
        },
        command,
    )


def _hollow_by_layer(layers: list[Layer], step: float) -> dict[int, dict]:
    report = {}
    for layer in layers:
        row = column_report(layer, step)
        if row["columns"]:
            report[layer.index] = row
    return report


def _sum_range(report: dict[int, dict], lo: int, hi: int | None) -> tuple[int, float]:
    columns = 0
    width = 0.0
    for index, row in report.items():
        if index < lo:
            continue
        if hi is not None and index > hi:
            continue
        columns += row["columns"]
        width += row["width_mm"]
    return columns, width


def gate_g9(base_layers: list[Layer], cand_layers: list[Layer], command: str, step: float = SAMPLE_MM) -> dict:
    base_report = _hollow_by_layer(base_layers, step)
    cand_report = _hollow_by_layer(cand_layers, step)
    base_fore, base_fore_w = _sum_range(base_report, 0, FOREFOOT_LAST)
    cand_fore, cand_fore_w = _sum_range(cand_report, 0, FOREFOOT_LAST)
    base_heel, base_heel_w = _sum_range(base_report, FOREFOOT_LAST + 1, None)
    cand_heel, cand_heel_w = _sum_range(cand_report, FOREFOOT_LAST + 1, None)

    def brief(report: dict[int, dict], lo: int, hi: int | None) -> dict:
        rows = {}
        for index in sorted(report):
            if index < lo or (hi is not None and index > hi):
                continue
            rows[str(index)] = {"columns": report[index]["columns"], "width_mm": report[index]["width_mm"], "runs": report[index]["runs"]}
        return rows

    passed = cand_fore == 0 and cand_heel <= base_heel
    return _result(
        "G9",
        passed,
        "forefoot layers <= 165: candidate hollow columns == 0; layers >= 166: candidate columns must not exceed baseline",
        {
            "sample_mm": step,
            "column_rule": "contiguous vertical rays whose shell is >= 3 mm thick, clear air between shell beads is > 1 mm, and no interior extrusion (inner wall or infill) occupies that air; a run counts only if its covered width is > 1 mm; columns = floor(width_mm) per such run",
            "baseline_forefoot_columns": base_fore,
            "candidate_forefoot_columns": cand_fore,
            "baseline_forefoot_width_mm": round(base_fore_w, 3),
            "candidate_forefoot_width_mm": round(cand_fore_w, 3),
            "baseline_above_165_columns": base_heel,
            "candidate_above_165_columns": cand_heel,
            "baseline_above_165_width_mm": round(base_heel_w, 3),
            "candidate_above_165_width_mm": round(cand_heel_w, 3),
            "baseline_forefoot_layers": brief(base_report, 0, FOREFOOT_LAST),
            "candidate_forefoot_layers": brief(cand_report, 0, FOREFOOT_LAST),
            "above_165_increased": cand_heel > base_heel,
        },
        command,
    )


def _ratios(layers: list[Layer], min_len: float) -> list[float]:
    values = []
    for layer in layers:
        for seg in layer.segments:
            if seg.kind != "extrude" or seg.typ != "Sparse infill" or not seg.e or seg.e <= 0:
                continue
            length = segment_length(seg)
            if length >= min_len:
                values.append(seg.e / length)
    return values


def gate_g10(base_layers: list[Layer], cand_layers: list[Layer], command: str) -> dict:
    baseline_ratios = _ratios(base_layers, E_RATIO_MIN_LEN)
    if baseline_ratios:
        low, high = min(baseline_ratios), max(baseline_ratios)
    else:
        low, high = None, None
    ratio_bad = []
    added_ratios = []
    wall_cross = []
    empty_travels = []
    for base, cand in zip(base_layers, cand_layers):
        added = _added_segments(base, cand)
        walls = [seg for seg in base.segments if seg.kind == "extrude" and seg.typ in SHELL]
        extrude_all = [seg for seg in cand.segments if seg.kind == "extrude"]
        for seg in added:
            if seg.kind != "extrude" or not seg.e or seg.e <= 0:
                continue
            length = segment_length(seg)
            if length < 0.05:
                continue
            ratio = seg.e / length
            if length >= E_RATIO_MIN_LEN:
                added_ratios.append(ratio)
            if low is not None and (ratio < low - 1e-9 or ratio > high + 1e-9) and len(ratio_bad) < 12:
                ratio_bad.append({"layer": cand.index, "e_per_mm": ratio, "length_mm": length, "type": seg.typ})
        for seg in added:
            if seg.kind != "travel":
                continue
            length = segment_length(seg)
            for wall in walls:
                if not segments_properly_cross(seg, wall):
                    continue
                side0, side1 = _signed_offset(seg, wall)
                depth = max(abs(side0), abs(side1))
                # A centerline nick while combing along the bead is not a traverse.
                # Through means an endpoint lies more than 0.2 mm on the other side of the wall line.
                if depth > THROUGH_WALL_MM:
                    wall_cross.append(
                        {
                            "layer": cand.index,
                            "x0": seg.x0,
                            "y0": seg.y0,
                            "x1": seg.x1,
                            "y1": seg.y1,
                            "length_mm": round(length, 3),
                            "retracted": seg.retracted,
                            "side_mm": [round(side0, 3), round(side1, 3)],
                        }
                    )
                    break
            if seg.retracted or length <= TRAVEL_EMPTY_MM:
                continue
            empty = _empty_span(seg, extrude_all)
            if empty > TRAVEL_EMPTY_MM:
                empty_travels.append(
                    {
                        "layer": cand.index,
                        "length_mm": round(length, 3),
                        "empty_span_mm": round(empty, 3),
                        "retracted": seg.retracted,
                    }
                )
    passed = not ratio_bad and not wall_cross and not empty_travels
    return _result(
        "G10",
        passed,
        (
            f"added extrusions longer than {E_RATIO_MIN_LEN} mm stay inside the baseline sparse-infill "
            f"E-per-mm range; an added travel fails if it crosses an outer-wall centerline and an endpoint "
            f"is more than {THROUGH_WALL_MM} mm on the other side of that line; an unretracted added travel "
            f"fails if more than {TRAVEL_EMPTY_MM} mm of it is clear of every extrusion bead"
        ),
        {
            "baseline_sparse_e_per_mm_min": low,
            "baseline_sparse_e_per_mm_max": high,
            "baseline_sparse_moves": len(baseline_ratios),
            "added_e_per_mm_min": min(added_ratios) if added_ratios else None,
            "added_e_per_mm_max": max(added_ratios) if added_ratios else None,
            "added_moves_checked": len(added_ratios),
            "e_per_mm_violations": ratio_bad[:12],
            "e_per_mm_violation_count": len(ratio_bad),
            "travels_through_outer_wall_count": len(wall_cross),
            "travels_through_outer_wall": wall_cross[:12],
            "unretracted_empty_travel_count": len(empty_travels),
            "unretracted_empty_travels": empty_travels[:12],
        },
        command,
    )


def _signed_offset(travel, wall) -> tuple[float, float]:
    dx = wall.x1 - wall.x0
    dy = wall.y1 - wall.y0
    length = math.hypot(dx, dy)
    if length < 1e-12:
        return 0.0, 0.0

    def signed(px: float, py: float) -> float:
        return ((px - wall.x0) * dy - (py - wall.y0) * dx) / length

    return signed(travel.x0, travel.y0), signed(travel.x1, travel.y1)


def _empty_span(travel, extrusions) -> float:
    """Longest contiguous stretch of the travel that is more than 0.2 mm clear of every extrusion bead."""
    length = segment_length(travel)
    if length <= 0:
        return 0.0
    step = 0.25
    count = max(2, int(length / step))
    empty_run = 0.0
    worst = 0.0
    for i in range(count + 1):
        t = i / count
        x = travel.x0 + t * (travel.x1 - travel.x0)
        y = travel.y0 + t * (travel.y1 - travel.y0)
        clearance = min((point_segment_distance(x, y, seg) - seg.width / 2.0) for seg in extrusions) if extrusions else 1e9
        if clearance > WALL_CLEARANCE_MM:
            empty_run += length / count
            worst = max(worst, empty_run)
        else:
            empty_run = 0.0
    return worst


def grade_pair(
    base_pre,
    base_layers,
    cand_pre,
    cand_layers,
    *,
    command: str,
    g1_files: list[str] | None = None,
    g1_numstat: list[dict] | None = None,
    g1_command: str | None = None,
    hollow_step: float = SAMPLE_MM,
    include_g2: bool = False,
    insole_base: list[str] | None = None,
    insole_cand: list[str] | None = None,
) -> list[dict]:
    """Grade one orthocad pair. G2 is the insole2 whole-file compare when those lines are passed."""
    results = []
    if g1_files is not None:
        results.append(gate_g1(g1_files, g1_command or command, g1_numstat))
    if include_g2 and insole_base is not None and insole_cand is not None:
        results.append(gate_g2(insole_base, insole_cand, command))
    results.append(gate_g3(base_layers, cand_layers, base_pre, cand_pre, command))
    results.append(gate_g4(base_layers, cand_layers, command))
    results.append(gate_g5(base_layers, cand_layers, command))
    results.append(gate_g6(base_layers, cand_layers, command))
    results.append(gate_g7(base_layers, cand_layers, command))
    results.append(gate_g8(base_layers, cand_layers, command))
    results.append(gate_g9(base_layers, cand_layers, command, hollow_step))
    results.append(gate_g10(base_layers, cand_layers, command))
    return results
