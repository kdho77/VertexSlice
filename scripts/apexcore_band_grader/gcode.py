"""Read OrcaSlicer belt G-code into layers and extrusion segments.

This reader is independent of the post-processor under test. Coordinates stay
in the file frame: X across the belt, Y off the belt (0 is the belt / plantar
face), Z constant inside a layer.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

STAMP_RE = re.compile(
    r"^; generated by OrcaSlicer \S+ on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}\s*$"
)
_WORD = re.compile(r"([XYZEF])([+-]?(?:\d+\.?\d*|\.\d+))")


@dataclass
class Segment:
    x0: float
    y0: float
    x1: float
    y1: float
    e: float | None
    f: float | None
    typ: str
    width: float
    kind: str
    retracted: bool
    line_no: int
    raw: str


@dataclass
class SeamMark:
    kind: str  # "start" at ;C_SEAM_START, or "travel" at a ";seam travel" move
    typ: str
    x: float
    y: float
    z: float | None


@dataclass
class Layer:
    index: int
    lines: list[str]
    z: float | None
    segments: list[Segment]
    seams: list[SeamMark]


def load_gcode(path: str) -> tuple[list[str], list[Layer]]:
    """Load a file. ``;TYPE:`` and ``;WIDTH:`` stay in effect until the next one, including across layers."""
    preamble: list[str] = []
    layers: list[Layer] = []
    bucket: list[str] | None = None
    x = y = z = None
    feed = None
    typ = "?"
    width = 1.0
    retracted = False

    def flush() -> None:
        nonlocal bucket
        if bucket is None:
            return
        z_value = None
        for line in bucket:
            if line.startswith(";Z:"):
                try:
                    z_value = float(line[3:].strip())
                except ValueError:
                    z_value = None
                break
        segments, seams, state = _parse_bucket(bucket, x, y, z, feed, typ, width, retracted)
        layers.append(Layer(index=len(layers), lines=bucket, z=z_value, segments=segments, seams=seams))
        # Carry modal state into the next layer. The caller updates the closed-over names.
        flush.state = state
        bucket = None

    flush.state = (x, y, z, feed, typ, width, retracted)
    with open(path, "r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            if line.startswith(";LAYER_CHANGE"):
                flush()
                x, y, z, feed, typ, width, retracted = flush.state
                bucket = [line]
            elif bucket is None:
                preamble.append(line)
            else:
                bucket.append(line)
    flush()
    return preamble, layers


def _parse_bucket(lines, x, y, z, feed, typ, width, retracted):
    segments: list[Segment] = []
    seams: list[SeamMark] = []
    for line_no, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith(";TYPE:"):
            typ = stripped[6:].strip()
            continue
        if stripped.startswith(";WIDTH:"):
            try:
                width = float(stripped[7:])
            except ValueError:
                pass
            continue
        if stripped.startswith(";C_SEAM_START") and x is not None and y is not None:
            seams.append(SeamMark("start", typ, x, y, z))
            continue
        if not stripped.startswith(("G0", "G1")):
            continue

        body, _, comment = stripped.partition(";")
        words = {match.group(1): float(match.group(2)) for match in _WORD.finditer(body)}
        nx = words.get("X", x)
        ny = words.get("Y", y)
        nz = words.get("Z", z)
        if "F" in words:
            feed = words["F"]
        e_val = words.get("E")
        moved = (
            x is not None
            and y is not None
            and nx is not None
            and ny is not None
            and (nx != x or ny != y)
        )
        if e_val is not None and e_val < 0 and not moved:
            kind = "retract"
            retracted = True
        elif e_val is not None and e_val > 0 and not moved:
            kind = "prime"
            retracted = False
        elif moved and e_val is not None and e_val > 0:
            kind = "extrude"
        elif moved:
            kind = "travel"
        elif "F" in words:
            kind = "feed"
        else:
            kind = "other"

        if kind in ("extrude", "travel") and x is not None and y is not None and nx is not None and ny is not None:
            segments.append(
                Segment(
                    x0=x,
                    y0=y,
                    x1=nx,
                    y1=ny,
                    e=e_val,
                    f=feed,
                    typ=typ,
                    width=width,
                    kind=kind,
                    retracted=retracted,
                    line_no=line_no,
                    raw=stripped,
                )
            )
            if kind == "extrude":
                retracted = False
        if "seam travel" in comment and nx is not None and ny is not None:
            seams.append(SeamMark("travel", typ, nx, ny, nz))
        x, y, z = nx, ny, nz
    return segments, seams, (x, y, z, feed, typ, width, retracted)


def stamp_diffs(base: list[str], cand: list[str]) -> list[dict]:
    """Line differences. A slicer timestamp comment is kind 'stamp'; anything else is 'other'."""
    if len(base) != len(cand):
        return [{"kind": "length", "base": len(base), "cand": len(cand)}]
    diffs = []
    for index, (left, right) in enumerate(zip(base, cand), start=1):
        if left == right:
            continue
        left_s, right_s = left.strip(), right.strip()
        kind = "stamp" if STAMP_RE.match(left_s) and STAMP_RE.match(right_s) else "other"
        diffs.append({"kind": kind, "line": index, "base": left_s[:240], "cand": right_s[:240]})
    return diffs


def line_delta(base: list[str], cand: list[str]) -> tuple[bool, list[int], list[int]]:
    """Align two layer listings.

    Returns (baseline_unchanged, added candidate indexes, missing baseline indexes).
    Inserted lines are added. A replaced or deleted baseline line is missing, which
    fails the "only additions" rule, and the replacement text is still reported as
    added so later gates can see it.
    """
    import difflib

    if base == cand:
        return True, [], []
    matcher = difflib.SequenceMatcher(a=base, b=cand, autojunk=False)
    added: list[int] = []
    missing: list[int] = []
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag == "insert":
            added.extend(range(j1, j2))
        elif tag == "delete":
            missing.extend(range(i1, i2))
        elif tag == "replace":
            missing.extend(range(i1, i2))
            added.extend(range(j1, j2))
    return not missing, added, missing
