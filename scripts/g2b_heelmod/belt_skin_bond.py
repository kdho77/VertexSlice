#!/usr/bin/env python3
"""Close belt skin air from the inside, on machine-Y G-code.

Beads are planned in virtual Y and emitted at Y_mach = sqrt(2) * Y_virt
without a wider bead. On the thin toe the virtual gap is under the minimum
bead, so the slicer leaves a slot with nothing in it. Growing that missing
bead in the planner never fires on SAMPLE_Top.

This pass runs after the seam and the crossing cleanup. It tiles each open
slot with two strips that start and end on an existing extrusion vertex, so
the added path is all extrusion: travel does not grow, and no outer-wall
point is added. ApexLight beads that are already in the file are not widened.
"""
from __future__ import annotations

import hashlib
import math
import os
import re
import statistics
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
if str(REPO / "validation") not in sys.path:
    sys.path.insert(0, str(REPO / "validation"))

from belt_skin_gate import CAP  # noqa: E402

RASTER_MM = 0.2
TOUCH_MM = 0.02
# A gyroid body is thicker than this. Skin pockets on SAMPLE_Top are not.
MAX_THICK_MM = 5.0
# Wider than this, the two strips would pass 1.6 mm, or the void is infill.
MAX_SLOT_MM = 3.1
# A bead narrower than this cannot be printed from a 1 mm nozzle. The old
# two-strip fill went down to 0.05 mm and the machine cannot lay it down.
MIN_WIDTH_MM = 0.45
MIN_LEN = 0.1
OVERLAP_MM = 0.0
TOE_END = 0.30
BAND_SPLIT = 0.15
# High ceiling. The volumetric cap is what actually limits a narrow strip.
# Ceiling only. A real strip is limited by the 35 mm3/s volumetric cap.
MAX_FEED = 60000.0
VOLUMETRIC_MM3_S = 35.0
FILAMENT_DIAMETER = 1.75


@dataclass
class Seg:
    x0: float
    y0: float
    x1: float
    y1: float
    width: float
    role: str
    line_index: int
    e: float = 0.0
    feed: float = 0.0


@dataclass
class Vertex:
    x: float
    y: float
    insert_after: int
    role: str
    width: float
    feed: float
    outer: bool


@dataclass
class Layer:
    z: float
    segs: list[Seg] = field(default_factory=list)
    vertices: list[Vertex] = field(default_factory=list)
    seconds: float = 0.0


@dataclass
class Sample:
    x: float
    lo: float
    hi: float


@dataclass
class Run:
    layer_index: int
    samples: list[Sample]
    anchor: Vertex
    band: str


_WORD = re.compile(r"([XYZEF])([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)")
_FILAMENT_ID = re.compile(r"^;\s*filament_settings_id\s*=\s*\"?([^\"\n]+)", re.M)
_TIME = re.compile(
    r"^; estimated printing time \([^)]*\) = (?:(\d+)h\s*)?(?:(\d+)m\s*)?(?:(\d+)s)?",
    re.M,
)
_FIL_MM = re.compile(r"^; filament used \[mm\] = ([0-9.]+)", re.M)
_FIL_G = re.compile(r"^; filament used \[g\] = ([0-9.]+)", re.M)
_SLOW = re.compile(r"slow_down_layer_time\s*=\s*([0-9.]+)")
_DIAM = re.compile(r"filament_diameter\s*[:=]\s*([0-9.]+)")
_GENERATED = re.compile(r"^; generated by\b", re.I)


def is_apex_light_gcode(text: str) -> bool:
    """True only for an ApexLight file. Forge and Bounce do not match."""
    match = _FILAMENT_ID.search(text)
    if match is None:
        return False
    name = match.group(1)
    if "ApexLight" not in name:
        return False
    if "Forge" in name or "Bounce" in name:
        return False
    return True


def strip_identity_lines(text: str) -> str:
    """Drop timestamp / generated-by header lines so two slices can be hashed."""
    kept = []
    for line in text.splitlines():
        if _GENERATED.match(line):
            continue
        kept.append(line)
    return "\n".join(kept) + "\n"


def gcode_md5(text: str) -> str:
    return hashlib.md5(strip_identity_lines(text).encode("utf-8", "replace")).hexdigest()


def _body(line: str) -> str:
    return line.split(";", 1)[0].strip()


def _words(line: str) -> dict[str, float]:
    return {m.group(1).upper(): float(m.group(2)) for m in _WORD.finditer(_body(line))}


def _is_move(line: str) -> bool:
    body = _body(line)
    return body.startswith("G0") or body.startswith("G1")


def _outer_role(role: str) -> bool:
    low = role.lower()
    return low.startswith("outer") or "overhang" in low


def _relative_e(text: str) -> bool:
    """Mode in effect when extrusion starts. The end script flips back to M82."""
    relative = None
    for line in text.splitlines():
        body = _body(line)
        if body.startswith("M83"):
            relative = True
        elif body.startswith("M82"):
            relative = False
        elif body.startswith(("G0", "G1")) and "E" in _words(line):
            if _words(line).get("E", 0.0) > 0.0:
                if relative is not None:
                    return relative
                break
    return "use_relative_e_distances = 1" in text


def _min_layer_time(text: str) -> float:
    match = _SLOW.search(text)
    if match is None:
        return 4.0
    return float(match.group(1))


def _diameter(text: str) -> float:
    match = _DIAM.search(text)
    if match is None:
        return FILAMENT_DIAMETER
    return float(match.group(1))


def _parse(text: str) -> tuple[list[str], list[Layer], float]:
    lines = text.splitlines()
    layers: list[Layer] = []
    current: Layer | None = None
    role = ""
    width = 1.0
    feed = 3000.0
    accel = 8000.0
    x = y = None
    rates: list[float] = []
    for index, raw in enumerate(lines):
        line = raw.strip()
        if line.startswith(";TYPE:"):
            role = line.split(":", 1)[1].strip()
            continue
        if line.startswith(";WIDTH:"):
            try:
                width = float(line.split(":", 1)[1])
            except ValueError:
                pass
            continue
        if line.startswith(";LAYER_CHANGE"):
            current = None
            continue
        if line.startswith(";Z:"):
            try:
                z = float(line.split(":", 1)[1])
            except ValueError:
                continue
            current = Layer(z=z)
            layers.append(current)
            continue
        if line.startswith("M204"):
            match = re.search(r"S([0-9.]+)", line)
            if match:
                accel = float(match.group(1))
            continue
        if not _is_move(line):
            continue
        words = _words(line)
        if "F" in words:
            feed = words["F"]
        nx = words.get("X", x)
        ny = words.get("Y", y)
        de = words["E"] if "E" in words else 0.0
        dist = 0.0
        if x is not None and y is not None and nx is not None and ny is not None:
            dist = math.hypot(nx - x, ny - y)
        if current is not None and dist > 0.0 and x is not None and nx is not None:
            speed = feed / 60.0
            if de > 1e-9 and speed > 0.0:
                current.seconds += dist / speed
            elif speed > 0.0 and accel > 0.0 and dist > 0.05:
                accel_dist = speed * speed / (2.0 * accel)
                if dist >= 2.0 * accel_dist:
                    current.seconds += 2.0 * (speed / accel) + (dist - 2.0 * accel_dist) / speed
                else:
                    current.seconds += 2.0 * math.sqrt(dist / accel)
        if (
            current is not None
            and de > 1e-9
            and dist > 0.0
            and x is not None
            and y is not None
            and nx is not None
            and ny is not None
        ):
            current.segs.append(Seg(x, y, nx, ny, width, role, index, de, feed))
            if width > 0.05 and abs(nx - x) >= abs(ny - y):
                rates.append(de / (dist * width))
            start_at = index - 1
            if start_at >= 0:
                current.vertices.append(Vertex(x, y, start_at, role, width, feed, _outer_role(role)))
            current.vertices.append(Vertex(nx, ny, index, role, width, feed, _outer_role(role)))
        if nx is not None:
            x, y = nx, ny
    factor = statistics.median(rates) if rates else 0.15
    if not math.isfinite(factor) or factor <= 0.0:
        factor = 0.15
    factor = min(max(factor, 0.02), 1.5)
    return lines, layers, factor


def _band(z: float, z0: float, z1: float) -> str | None:
    span = z1 - z0
    frac = 0.0 if span <= 1e-6 else (z - z0) / span
    # Inclusive of the layer that lands on the 30% boundary (SAMPLE_Top layer 130).
    if frac < -1e-9 or frac > TOE_END + 1e-4:
        return None
    if frac <= BAND_SPLIT:
        return "0-15"
    return "15-30"


def _merge(intervals: list[tuple[float, float]]) -> list[tuple[float, float]]:
    if not intervals:
        return []
    intervals = sorted(intervals)
    out = [intervals[0]]
    for lo, hi in intervals[1:]:
        plo, phi = out[-1]
        if lo <= phi + TOUCH_MM:
            out[-1] = (plo, max(phi, hi))
        else:
            out.append((lo, hi))
    return out


def _gaps_at(intervals: list[tuple[float, float]]) -> list[tuple[float, float]]:
    merged = _merge(intervals)
    if len(merged) < 2:
        return []
    gaps: list[tuple[float, float]] = []
    group = [merged[0]]
    for iv in merged[1:]:
        if iv[0] - group[-1][1] > MAX_SLOT_MM:
            gaps.extend(_group_gaps(group))
            group = [iv]
        else:
            group.append(iv)
    gaps.extend(_group_gaps(group))
    return gaps


def _group_gaps(group: list[tuple[float, float]]) -> list[tuple[float, float]]:
    if group[-1][1] - group[0][0] > MAX_THICK_MM:
        return []
    found = []
    for left, right in zip(group, group[1:]):
        gap = right[0] - left[1]
        if gap > TOUCH_MM:
            found.append((left[1], right[0]))
    return found


def _layer_gaps(layer: Layer) -> dict[float, list[tuple[float, float]]]:
    """X -> open slots. X is on the 0.2 mm raster."""
    if not layer.segs:
        return {}
    bins: dict[int, list[Seg]] = {}
    xs: list[float] = []
    for seg in layer.segs:
        lo = min(seg.x0, seg.x1)
        hi = max(seg.x0, seg.x1)
        xs.append(lo)
        xs.append(hi)
        a = int(math.floor(lo))
        b = int(math.floor(hi))
        for key in range(a, b + 1):
            bins.setdefault(key, []).append(seg)
    x0 = min(xs)
    x1 = max(xs)
    # Integer raster. Adding 0.2 repeatedly drifts off the bin boundary and
    # a column then misses the bead that closes it.
    i0 = math.floor(x0 / RASTER_MM)
    i1 = math.ceil(x1 / RASTER_MM)
    found: dict[float, list[tuple[float, float]]] = {}
    for i in range(i0, i1 + 1):
        x = i * RASTER_MM
        key = int(math.floor(x))
        intervals: list[tuple[float, float]] = []
        seen: set[int] = set()
        for key_i in (key - 1, key, key + 1):
            for seg in bins.get(key_i, ()):
                ident = id(seg)
                if ident in seen:
                    continue
                seen.add(ident)
                span = seg.x1 - seg.x0
                if abs(span) < 1e-9:
                    # A vertical bead belongs to its own column only.
                    if abs(x - seg.x0) > 0.05:
                        continue
                    y = (seg.y0 + seg.y1) / 2.0
                else:
                    t = (x - seg.x0) / span
                    if t < 0.0 or t > 1.0:
                        over = (0.0 - t) * abs(span) if t < 0.0 else (t - 1.0) * abs(span)
                        if over > 0.05:
                            continue
                    t = min(1.0, max(0.0, t))
                    y = seg.y0 + t * (seg.y1 - seg.y0)
                half = max(seg.width, 0.0) / 2.0
                intervals.append((y - half, y + half))
        gaps = _gaps_at(intervals)
        if gaps:
            found[round(x, 4)] = gaps
    return found


def _runs_for_layer(layer_index: int, layer: Layer, band: str) -> tuple[list[Run], int]:
    columns = _layer_gaps(layer)
    open_runs: list[list[Sample]] = []
    finished: list[list[Sample]] = []
    for x in sorted(columns):
        used: set[int] = set()
        for lo, hi in columns[x]:
            sample = Sample(x, lo, hi)
            placed = False
            for index, run in enumerate(open_runs):
                if index in used:
                    continue
                last = run[-1]
                if x - last.x > RASTER_MM * 1.5:
                    continue
                if abs(last.lo - lo) > 0.4 or abs(last.hi - hi) > 0.4:
                    continue
                run.append(sample)
                used.add(index)
                placed = True
                break
            if not placed:
                open_runs.append([sample])
                used.add(len(open_runs) - 1)
        still: list[list[Sample]] = []
        for index, run in enumerate(open_runs):
            if index in used:
                still.append(run)
            else:
                finished.append(run)
        open_runs = still
    finished.extend(open_runs)
    runs: list[Run] = []
    unanchored = 0
    for samples in finished:
        if not samples:
            continue
        anchor = _anchor(layer, samples)
        if anchor is None:
            unanchored += 1
            continue
        runs.append(Run(layer_index, samples, anchor, band))
    return runs, unanchored


def _anchor(layer: Layer, samples: list[Sample]) -> Vertex | None:
    x0 = samples[0].x
    x1 = samples[-1].x
    # The slot drifts. Use the median upper edge as the preferred Y.
    hi = statistics.median(s.hi for s in samples)
    lo = statistics.median(s.lo for s in samples)
    best: tuple[tuple[float, float, float], Vertex] | None = None
    for vertex in layer.vertices:
        if vertex.x < x0 - 0.5 or vertex.x > x1 + 0.5:
            continue
        if vertex.y < lo - 1.5 or vertex.y > hi + 1.5:
            continue
        end = min(abs(vertex.x - x0), abs(vertex.x - x1))
        score = (1.0 if vertex.outer else 0.0, end, abs(vertex.y - hi))
        if best is None or score < best[0]:
            best = (score, vertex)
    return None if best is None else best[1]


def measure_toe_air(text: str) -> dict:
    """0.2 mm raster of toe-band skin air. Volume uses the median belt Z step."""
    _lines, layers, _factor = _parse(text)
    return _measure_layers(layers)


def _measure_layers(layers: list[Layer]) -> dict:
    zs = [layer.z for layer in layers]
    z0 = min(zs) if zs else 0.0
    z1 = max(zs) if zs else 0.0
    deltas = [b.z - a.z for a, b in zip(layers, layers[1:]) if b.z > a.z + 1e-6]
    pitch = statistics.median(deltas) if deltas else 0.46
    bands = {
        "0-15": {"air_mm3": 0.0, "layers": 0, "columns": 0, "worst_mm": 0.0},
        "15-30": {"air_mm3": 0.0, "layers": 0, "columns": 0, "worst_mm": 0.0},
    }
    seen_layer = {"0-15": set(), "15-30": set()}
    for layer in layers:
        band = _band(layer.z, z0, z1)
        if band is None:
            continue
        columns = _layer_gaps(layer)
        if not columns:
            continue
        for gaps in columns.values():
            for lo, hi in gaps:
                gap = hi - lo
                bands[band]["air_mm3"] += gap * RASTER_MM * pitch
                bands[band]["columns"] += 1
                if gap > bands[band]["worst_mm"]:
                    bands[band]["worst_mm"] = gap
        if columns:
            seen_layer[band].add(layer.z)
    for name in bands:
        bands[name]["layers"] = len(seen_layer[name])
        bands[name]["air_mm3"] = round(bands[name]["air_mm3"], 1)
        bands[name]["worst_mm"] = round(bands[name]["worst_mm"], 3)
    return {"z0": z0, "z1": z1, "z_pitch": round(pitch, 4), "bands": bands}


def _strip_points(samples: list[Sample]) -> list[tuple[float, float, float]] | None:
    """Even two-strip path. Ends on the same X it started, inside the slot."""
    upper: list[tuple[float, float, float]] = []
    lower: list[tuple[float, float, float]] = []
    for sample in samples:
        slot = sample.hi - sample.lo
        if slot <= TOUCH_MM or slot > MAX_SLOT_MM:
            return None
        width = slot / 2.0 + OVERLAP_MM
        if width > CAP + 1e-6:
            return None
        lower.append((sample.x, sample.lo + slot / 4.0, width))
        upper.append((sample.x, sample.lo + 3.0 * slot / 4.0, width))
    return upper + list(reversed(lower))


def _efix_scale(dx: float, dy: float) -> float:
    den = math.sqrt(dx * dx + 2.0 * dy * dy)
    if den <= 0.0:
        return 1.0
    return math.hypot(dx, dy) / den


def _feed_for(width: float, factor: float, area: float) -> float:
    mm3_per_mm = width * factor * area
    if mm3_per_mm <= 1e-9:
        return MAX_FEED
    speed = min(MAX_FEED / 60.0, VOLUMETRIC_MM3_S / mm3_per_mm)
    return max(600.0, speed * 60.0)


def _fmt(value: float, places: int) -> str:
    return f"{value:.{places}f}"


def _render(run: Run, factor: float, area: float) -> tuple[list[str], float, float]:
    samples = run.samples
    if abs(run.anchor.x - samples[-1].x) < abs(run.anchor.x - samples[0].x):
        samples = list(reversed(samples))
    points = _strip_points(samples)
    if not points:
        return [], 0.0, 0.0
    ax, ay = run.anchor.x, run.anchor.y
    path = [(ax, ay, points[0][2]), *points, (ax, ay, points[-1][2])]
    lines = [";TYPE:Gap infill", f";WIDTH:{_fmt(points[0][2], 3)}", f"; belt_skin_bond run band={run.band}"]
    added_e = 0.0
    added_s = 0.0
    last_width = None
    for (x0, y0, _w0), (x1, y1, w1) in zip(path, path[1:]):
        dx, dy = x1 - x0, y1 - y0
        dist = math.hypot(dx, dy)
        if dist < 1e-4:
            continue
        width = min(CAP, max(w1, 0.05))
        if last_width is None or abs(width - last_width) > 0.02:
            lines.append(f";WIDTH:{_fmt(width, 3)}")
            last_width = width
        e = dist * width * factor * _efix_scale(dx, dy)
        feed = _feed_for(width, factor, area)
        added_e += e
        added_s += dist / (feed / 60.0)
        lines.append(
            f"G1 X{_fmt(x1, 4)} Y{_fmt(y1, 4)} E{_fmt(e, 5)} F{_fmt(feed, 0)}"
        )
    if len(lines) <= 3:
        return [], 0.0, 0.0
    # Hand the following move back its role, width, and feed.
    if run.anchor.role:
        lines.append(f";TYPE:{run.anchor.role}")
    if run.anchor.width > 0.0:
        lines.append(f";WIDTH:{_fmt(run.anchor.width, 5)}")
    if run.anchor.feed > 0.0:
        lines.append(f"G1 F{_fmt(run.anchor.feed, 0)}")
    return lines, added_e, added_s


def _apply_footer(text: str, added_mm: float, added_s: float) -> str:
    def _time_sub(match: re.Match[str]) -> str:
        hours = int(match.group(1) or 0)
        minutes = int(match.group(2) or 0)
        seconds = int(match.group(3) or 0)
        total = hours * 3600 + minutes * 60 + seconds + added_s
        whole = int(round(total))
        h, rem = divmod(whole, 3600)
        m, s = divmod(rem, 60)
        prefix = match.group(0).split("=", 1)[0]
        return f"{prefix}= {h}h {m}m {s}s"

    text = _TIME.sub(_time_sub, text, count=1)

    def _mm_sub(match: re.Match[str]) -> str:
        return f"; filament used [mm] = {float(match.group(1)) + added_mm:.2f}"

    text = _FIL_MM.sub(_mm_sub, text, count=1)
    mm = _FIL_MM.search(text)
    # The mm line was already updated. Scale grams by the same ratio.
    old_mm_match = re.search(r"filament used \[mm\] = ([0-9.]+)", text)
    # added_mm is already inside the new mm value. Recover the old mm.
    if old_mm_match and added_mm > 0.0:
        new_mm = float(old_mm_match.group(1))
        old_mm = new_mm - added_mm

        def _g_sub(match: re.Match[str]) -> str:
            old_g = float(match.group(1))
            if old_mm <= 1e-6:
                return match.group(0)
            return f"; filament used [g] = {old_g * (new_mm / old_mm):.2f}"

        text = _FIL_G.sub(_g_sub, text, count=1)

        def _scale(match: re.Match[str]) -> str:
            return f"{match.group(1)}{float(match.group(2)) * (new_mm / old_mm):.2f}"

        text = re.sub(r"(; filament used \[cm3\] = )([0-9.]+)", _scale, text, count=1)
        text = re.sub(r"(; total filament used \[g\] = )([0-9.]+)", _scale, text)
    return text


def _layer_bins(layer: Layer) -> dict[int, list[Seg]]:
    bins: dict[int, list[Seg]] = {}
    for seg in layer.segs:
        lo = int(math.floor(min(seg.x0, seg.x1)))
        hi = int(math.floor(max(seg.x0, seg.x1)))
        for key in range(lo, hi + 1):
            bins.setdefault(key, []).append(seg)
    return bins


def _point_on(seg: Seg, x: float) -> float | None:
    span = seg.x1 - seg.x0
    if abs(span) < 1e-9:
        if abs(seg.x0 - x) > RASTER_MM * 1.5:
            return None
        return (seg.y0 + seg.y1) / 2.0
    t = (x - seg.x0) / span
    if t < -0.02 or t > 1.02:
        return None
    t = min(1.0, max(0.0, t))
    return seg.y0 + t * (seg.y1 - seg.y0)


def _facing_gap(bins: dict[int, list[Seg]], x: float, y: float, width: float) -> tuple[float, float] | None:
    """Gap this bead touches, and the width of the bead on the other side."""
    raw: list[tuple[float, float, float]] = []
    for seg in bins.get(int(math.floor(x)), ()):
        yy = _point_on(seg, x)
        if yy is None:
            continue
        half = max(seg.width, 0.0) / 2.0
        raw.append((yy - half, yy + half, seg.width))
    if not raw:
        return None
    raw.sort()
    merged: list[list[float]] = [[*raw[0]]]
    for lo, hi, wide in raw[1:]:
        if lo <= merged[-1][1] + TOUCH_MM:
            merged[-1][1] = max(merged[-1][1], hi)
            merged[-1][2] = max(merged[-1][2], wide)
        else:
            merged.append([lo, hi, wide])
    if merged[-1][1] - merged[0][0] > MAX_THICK_MM:
        return None
    half = width / 2.0
    mine = None
    for index, (lo, hi, _wide) in enumerate(merged):
        if abs(lo - (y - half)) < 0.35 and abs(hi - (y + half)) < 0.35:
            mine = index
            break
    if mine is None:
        return None
    best: tuple[float, float] | None = None
    lo, hi, _wide = merged[mine]
    if mine + 1 < len(merged):
        gap = merged[mine + 1][0] - hi
        if TOUCH_MM < gap <= MAX_SLOT_MM:
            best = (gap, merged[mine + 1][2])
    if mine > 0:
        gap = lo - merged[mine - 1][1]
        if TOUCH_MM < gap <= MAX_SLOT_MM and (best is None or gap > best[0]):
            best = (gap, merged[mine - 1][2])
    return best


def _plan_widen(layers: list[Layer], z0: float, z1: float) -> dict[int, float]:
    """Grow a bead toward the slot, never past 1.6 mm and never past the narrowest gap.

    The centreline stays where it is. A bead already wider than 1.6 mm is left
    alone, so ApexLight does not gain another bead over that cap. Growth is the
    minimum along the segment: where the slot is wider, the fill pass closes it.
    """
    planned: dict[int, float] = {}
    for layer in layers:
        if _band(layer.z, z0, z1) is None:
            continue
        bins = _layer_bins(layer)
        for seg in layer.segs:
            if seg.width > CAP + 1e-6 or seg.e <= 1e-9:
                continue
            length = math.hypot(seg.x1 - seg.x0, seg.y1 - seg.y0)
            if length < 0.2:
                continue
            room = CAP - seg.width
            if room <= 0.01:
                continue
            steps = max(2, int(length / 0.5))
            shares: list[float] = []
            covered = True
            for step in range(steps + 1):
                t = step / steps
                x = seg.x0 + t * (seg.x1 - seg.x0)
                y = seg.y0 + t * (seg.y1 - seg.y0)
                faced = _facing_gap(bins, x, y, seg.width)
                if faced is None:
                    covered = False
                    break
                gap, other_w = faced
                other_room = 0.0 if other_w > CAP + 1e-6 else max(0.0, CAP - other_w)
                need = max(0.0, gap - TOUCH_MM)
                share = min(room, max(need / 2.0, need - other_room))
                shares.append(share)
            if not covered or not shares:
                continue
            growth = min(shares)
            if growth <= 0.01:
                continue
            planned[seg.line_index] = seg.width + growth
    return planned


def _rewrite_extrusion(line: str, scale: float, feed: float | None) -> str:
    body, sep, comment = line.partition(";")

    def _sub(match: re.Match[str]) -> str:
        letter = match.group(1).upper()
        if letter == "E":
            return "E" + _fmt(float(match.group(2)) * scale, 5)
        if letter == "F" and feed is not None:
            return "F" + _fmt(feed, 0)
        return match.group(0)

    return _WORD.sub(_sub, body) + sep + comment


def _layer_height(text: str) -> float:
    match = re.search(r"^;\s*layer_height\s*=\s*([0-9.]+)", text, re.M)
    return float(match.group(1)) if match else 0.46


def _feed_cap_mm_min(text: str) -> float:
    """Slowest of gap infill, solid infill, and the machine max, in mm/min."""

    def read(key: str, default: float) -> float:
        match = re.search(rf"^;\s*{key}\s*=\s*([0-9.]+)", text, re.M)
        return float(match.group(1)) if match else default

    mm_s = min(read("gap_infill_speed", 26.0), read("internal_solid_infill_speed", 26.0))
    machine = min(read("machine_max_speed_x", 500.0), read("machine_max_speed_y", 500.0))
    return min(mm_s, machine) * 60.0


def _e_width(seg: Seg, area: float, lh: float) -> float:
    dist = math.hypot(seg.x1 - seg.x0, seg.y1 - seg.y0)
    if dist <= 1e-6 or lh <= 0.0 or area <= 0.0:
        return seg.width
    return seg.e * area / (dist * lh)


def _filament_budget_mm(text: str) -> float:
    """Millimetres of filament still inside +3% of the published live grams."""
    published = None
    match = re.search(r'filament_settings_id\s*=\s*"?([^"\n]+)', text)
    if match:
        name = match.group(1)
        if "ApexCore" in name and "Forge" not in name:
            published = 84.05
        elif "ApexLight" in name and "Forge" not in name and "Bounce" not in name:
            published = 75.70
    mm = _FIL_MM.search(text)
    grams = _FIL_G.search(text)
    if published is None or mm is None or grams is None:
        return 1.0e9
    footer_mm = float(mm.group(1))
    footer_g = float(grams.group(1))
    if footer_g <= 1e-6:
        return 0.0
    room_g = published * 1.03 - footer_g
    if room_g <= 0.0:
        return 0.0
    return room_g * footer_mm / footer_g


def _widen_plan(
    layers: list[Layer],
    z0: float,
    z1: float,
    area: float,
    lh: float,
    feed_cap: float,
    budget_mm: float,
) -> dict[int, tuple[float, float, float | None]]:
    """Grow an existing non-outer bead until it meets the nearer skin.

    The centreline stays put, so the outer wall path and the seams do not move.
    Nothing is emitted under 0.45 mm or over the profile feed cap. A slot that
    cannot take a legal bead is left alone.
    """
    candidates: list[tuple[float, float, int, tuple[float, float, float | None]]] = []
    for layer in layers:
        if _band(layer.z, z0, z1) is None:
            continue
        widths = {id(seg): _e_width(seg, area, lh) for seg in layer.segs}
        bins: dict[int, list[Seg]] = defaultdict(list)
        for seg in layer.segs:
            lo = int(math.floor(min(seg.x0, seg.x1)))
            hi = int(math.floor(max(seg.x0, seg.x1)))
            for key in range(lo, hi + 1):
                bins[key].append(seg)
        for seg in layer.segs:
            if _outer_role(seg.role):
                continue
            dist = math.hypot(seg.x1 - seg.x0, seg.y1 - seg.y0)
            if dist < MIN_LEN or abs(seg.y1 - seg.y0) > abs(seg.x1 - seg.x0):
                continue
            own = widths[id(seg)]
            if own <= 0.05 or own > CAP:
                continue
            steps = max(1, int(dist / 0.2))
            min_gap = None
            thin = False
            for step in range(steps + 1):
                t = step / steps
                x = seg.x0 + t * (seg.x1 - seg.x0)
                y = seg.y0 + t * (seg.y1 - seg.y0)
                intervals = []
                for other in bins.get(int(math.floor(x)), ()):
                    span = other.x1 - other.x0
                    if abs(span) < 1e-9:
                        continue
                    tt = (x - other.x0) / span
                    if tt < 0.0 or tt > 1.0:
                        continue
                    yy = other.y0 + tt * (other.y1 - other.y0)
                    half = widths[id(other)] / 2.0
                    intervals.append((yy - half, yy + half, other is seg))
                intervals.sort()
                me = next((i for i, row in enumerate(intervals) if row[2]), None)
                if me is None:
                    continue
                if intervals[-1][1] - intervals[0][0] > MAX_THICK_MM:
                    continue
                thin = True
                lo, hi, _me = intervals[me]
                for side in (me - 1, me + 1):
                    if side < 0 or side >= len(intervals):
                        continue
                    gap = (lo - intervals[side][1]) if side < me else (intervals[side][0] - hi)
                    if TOUCH_MM < gap <= MAX_SLOT_MM and (min_gap is None or gap < min_gap):
                        min_gap = gap
            if not thin or min_gap is None:
                continue
            grown = min(CAP, own + 2.0 * min_gap)
            if grown < MIN_WIDTH_MM:
                if (MIN_WIDTH_MM - own) / 2.0 <= min_gap + 1e-6:
                    grown = MIN_WIDTH_MM
                else:
                    continue
            if grown <= own + 0.01:
                continue
            new_e = grown * dist * lh / area
            new_feed = None
            if seg.feed > feed_cap + 1.0:
                new_feed = feed_cap
            candidates.append((new_e - seg.e, seg.line_index, own, new_e, grown, new_feed))
    # Every bead grows by the same fraction when the full close would pass the
    # filament cap. Dropping whole beads leaves the columns they covered open.
    total = sum(added for added, *_rest in candidates if added > 0.0)
    factor = 1.0 if total <= budget_mm or total <= 0.0 else budget_mm / total
    planned: dict[int, tuple[float, float, float | None]] = {}
    for added, line_index, own, new_e, grown, new_feed in candidates:
        if added <= 0.0 or grown <= 0.0:
            continue
        own_e = own * new_e / grown
        width = own + factor * (grown - own)
        if width < MIN_WIDTH_MM or width <= own + 0.01:
            continue
        planned[line_index] = (own_e + factor * (new_e - own_e), width, new_feed)
    return planned


def _rewrite_absolute(line: str, new_e: float, new_feed: float | None) -> str:
    body, sep, comment = line.partition(";")

    def _sub(match: re.Match[str]) -> str:
        letter = match.group(1).upper()
        if letter == "E":
            return "E" + _fmt(new_e, 5)
        if letter == "F" and new_feed is not None:
            return "F" + _fmt(new_feed, 0)
        return match.group(0)

    rewritten = _WORD.sub(_sub, body)
    if new_feed is not None and not re.search(r"F\s*-?(?:\d+\.?\d*|\.\d+)", body, re.I):
        rewritten = rewritten.rstrip() + f" F{_fmt(new_feed, 0)}"
    return rewritten + sep + comment


def bond_gcode(text: str, material: str = "apex_core") -> str:
    """Widen existing inner beads so they meet the skins.

    Hairline strips are not emitted. They are under 0.45 mm, faster than the
    machine, and they break the outer wall. No bead widened -> the same string.
    """
    if "; belt_skin_bond filled_runs=" in text:
        print(f"belt_skin_bond material={material} filled_runs=0 widened=0 already_bonded=1", flush=True)
        return text
    if not _relative_e(text):
        print(f"belt_skin_bond material={material} filled_runs=0 widened=0 relative_e=0", flush=True)
        return text
    lines, layers, _factor = _parse(text)
    if not layers:
        print(f"belt_skin_bond material={material} filled_runs=0 widened=0 layers=0", flush=True)
        return text
    zs = [layer.z for layer in layers]
    area = math.pi * (_diameter(text) / 2.0) ** 2
    lh = _layer_height(text)
    feed_cap = _feed_cap_mm_min(text)
    planned = _widen_plan(layers, min(zs), max(zs), area, lh, feed_cap, _filament_budget_mm(text))
    if not planned:
        print(
            f"belt_skin_bond material={material} filled_runs=0 widened=0 unanchored=0 layers=0",
            flush=True,
        )
        return text

    seg_by_line = {seg.line_index: seg for layer in layers for seg in layer.segs}
    added_mm = 0.0
    added_s = 0.0
    per_layer: dict[float, int] = {}
    for line_index, (new_e, _width, new_feed) in planned.items():
        seg = seg_by_line[line_index]
        added_mm += new_e - seg.e
        if new_feed is not None and seg.feed > 0.0:
            dist = math.hypot(seg.x1 - seg.x0, seg.y1 - seg.y0)
            added_s += dist / (new_feed / 60.0) - dist / (seg.feed / 60.0)
        per_layer[seg.line_index] = per_layer.get(seg.line_index, 0) + 1

    out_lines: list[str] = []
    active_width: float | None = None
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith(";WIDTH:"):
            try:
                active_width = float(stripped.split(":", 1)[1])
            except ValueError:
                pass
            out_lines.append(line)
            continue
        change = planned.get(index)
        if change is None:
            out_lines.append(line)
            continue
        _new_e, new_width, new_feed = change
        if active_width is None or abs(active_width - new_width) > 0.0005:
            out_lines.append(f";WIDTH:{_fmt(new_width, 4)}")
            active_width = new_width
        out_lines.append(_rewrite_absolute(line, _new_e, new_feed))
    comment = f"; belt_skin_bond filled_runs=0 widened={len(planned)}"
    placed = False
    for index, line in enumerate(out_lines):
        if line.startswith("; estimated printing time"):
            out_lines.insert(index, comment)
            placed = True
            break
    if not placed:
        out_lines.append(comment)
    joined = "\n".join(out_lines)
    if text.endswith("\n"):
        joined += "\n"
    joined = _apply_footer(joined, added_mm, added_s)
    print(
        f"belt_skin_bond material={material} filled_runs=0 widened={len(planned)} "
        f"unanchored=0 layers={len(per_layer)} added_mm={added_mm:.2f} added_s={added_s:.2f}",
        flush=True,
    )
    return joined


def _debug_gaps(layers: list[Layer], z0: float, z1: float) -> str:
    shown = 0
    parts = []
    for layer in layers:
        band = _band(layer.z, z0, z1)
        if band is None:
            continue
        columns = _layer_gaps(layer)
        if not columns or shown >= 3:
            continue
        x = next(iter(columns))
        parts.append(f"z={layer.z:.3f} band={band} x={x:.1f} gaps={columns[x][:2]}")
        shown += 1
    return " ".join(parts)


def bond_apex_light(text: str) -> str:
    """Last stage for ApexLight only. Forge, Bounce, and ApexCore pass through."""
    if os.environ.get("BELT_SKIN_BOND", "1") == "0":
        print("belt_skin_bond material=apex_light filled_runs=0 widened=0 disabled=1", flush=True)
        return text
    if not is_apex_light_gcode(text):
        return text
    return bond_gcode(text, material="apex_light")
