#!/usr/bin/env python3
"""Re-slice the locked ApexCore 95A profile and compare it to the printed file.

The printed G-code is not in the repo. This checks the stored event list and
per-feature E/mm (0.5%), and the sha256 when the bytes match. The slicer
timestamp line is the only header field that changes between runs; a match
with that line restored to the printed timestamp is reported as the same bytes.
"""
from __future__ import annotations

import gzip
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(HERE)]

from postprocess_g2b import feature_stats  # noqa: E402
from topfix_apexcore import retract_events, topfix  # noqa: E402

SUMMARY_PATH = HERE / "apexcore_95a_golden_summary.json"
LOCK_PATH = HERE / "apexcore_95a_locked.json"
GOLDEN_SHA = "1eb294be4315565e868c0960a569f4f4158253f41b69955dc15cd3da77fb826e"
GENERATED_PREFIX = "; generated by OrcaSlicer"
E_MM_TOL = 0.005


def load_summary() -> dict:
    return json.loads(SUMMARY_PATH.read_text())


def feature_rows(text: str) -> dict[str, dict[str, float]]:
    stats = feature_stats(text)
    return {
        name: {"e_per_mm": round(row["e_per_mm"], 6), "length_mm": round(row["length_mm"], 3)}
        for name, row in stats["features"].items()
    }


def normalize_timestamp(text: str, replacement: str) -> str:
    lines = text.splitlines(keepends=True)
    out = []
    for line in lines:
        if line.startswith(GENERATED_PREFIX):
            nl = "\n" if line.endswith("\n") else ""
            out.append(replacement + nl)
        else:
            out.append(line)
    return "".join(out)


def _slicer_bin() -> Path | None:
    env = os.environ.get("ORCA_SLICER_BIN", "/tmp/g2b/root/app/bin/orca-slicer")
    path = Path(env)
    return path if path.is_file() else None


def _resources() -> Path | None:
    env = os.environ.get("ORCA_RESOURCES", "/tmp/g2b/root/app/resources")
    path = Path(env)
    return path if (path / "profiles/IdeaFormer/filament/ApexCore.json").is_file() else None


def _ensure_stl() -> Path | None:
    env = os.environ.get("APEXCORE_STL")
    if env and Path(env).is_file():
        return Path(env)
    cached = Path("/tmp/g2b/procedural-default-round_2p5mm_belt270.stl")
    if cached.is_file():
        return cached
    gz = Path("/cursor/stores/bot/vsbrief/insole_round_2p5mm.stl.gz")
    if not gz.is_file():
        return None
    src_dir = Path("/tmp/g2b/src")
    if not (src_dir / "validation/stl_preprocess.py").is_file():
        src_dir.mkdir(parents=True, exist_ok=True)
        archive = subprocess.run(
            [
                "git",
                "archive",
                "def8eff480",
                "validation/stl_preprocess.py",
                "validation/apex_bed_placement.py",
                "validation/apex_insole_tunables.py",
            ],
            cwd=HERE.parents[1],
            check=True,
            capture_output=True,
        )
        subprocess.run(["tar", "-x", "-C", str(src_dir)], input=archive.stdout, check=True)
    raw = Path("/tmp/g2b/insole_round_2p5mm.stl")
    if not raw.is_file():
        raw.write_bytes(gzip.decompress(gz.read_bytes()))
    sys.path[:0] = [str(src_dir / "validation")]
    from stl_preprocess import prepare_orthocad_insole_stl

    _out, meta = prepare_orthocad_insole_stl(raw, x_center_mm=140.0, print_direction="toe_first")
    cached.write_bytes(Path(meta["preprocessed_stl"]).read_bytes())
    return cached


def run_pipeline(work: Path, stl: Path, dest: Path) -> None:
    env = os.environ.copy()
    lib = "/tmp/g2b/root/usr/lib/x86_64-linux-gnu"
    env["LD_LIBRARY_PATH"] = lib + ((":" + env["LD_LIBRARY_PATH"]) if env.get("LD_LIBRARY_PATH") else "")
    env.setdefault("ORCA_SLICER_BIN", "/tmp/g2b/root/app/bin/orca-slicer")
    env.setdefault("ORCA_RESOURCES", "/tmp/g2b/root/app/resources")
    raw = work / "raw.gcode"
    matched = work / "matched.gcode"
    pulled = work / "pullback.gcode"
    subprocess.run(
        [sys.executable, str(HERE / "slice_apexcore_g2b.py"), "core", str(work), str(stl), str(raw)],
        check=True,
        env=env,
    )
    subprocess.run(
        [sys.executable, str(HERE / "postprocess_g2b.py"), "match", str(raw), str(matched)],
        check=True,
    )
    subprocess.run(
        [sys.executable, str(HERE / "pullback_v2.py"), str(matched), str(pulled)],
        check=True,
    )
    subprocess.run(
        [sys.executable, str(HERE / "topfix_apexcore.py"), str(pulled), str(dest)],
        check=True,
    )


class ApexCore95ALocked(unittest.TestCase):
    def test_profile_is_locked(self) -> None:
        lock = json.loads(LOCK_PATH.read_text())
        self.assertEqual(lock["status"], "LOCKED")
        self.assertIn("Kendon", lock["approval"])
        self.assertEqual(lock["sha256"], GOLDEN_SHA)
        self.assertEqual(lock["settings"]["nozzle_temperature"]["value"], "225")
        self.assertEqual(lock["settings"]["layer_height"]["value"], "0.46")
        self.assertEqual(lock["settings"]["filament_retraction_length"]["value"], "0")
        self.assertEqual(lock["settings"]["retract_when_changing_layer"]["value"], "0")
        self.assertEqual(lock["fan_gcode"], ["M106 S127", "M106 P1 S63"])

    def test_topfix_keeps_a_belt_seam_and_drops_a_locked_near_top_pair(self) -> None:
        # Landing (104.294, 3.036) is one of the 19. The extrusion at the same
        # X is 0.1 mm above it, so the pair is within 2.5 mm of that highest
        # point. The belt seam is the highest extrusion in its own ±1 mm band
        # and is not in the no-counterpart table, so its retract stays.
        lines = [
            ";LAYER_CHANGE\n",
            ";C seam travel: lift + direct\n",
            "G1 E-0.5 F1800\n",
            "G1 Y1.483 F12720 ;lift\n",
            "G1 X104.294 Y3.436 F12720 ;seam travel\n",
            "G1 Y3.036 F12720 ;lower\n",
            "G1 E0.45 F1800\n",
            "G1 F12720\n",
            "G1 X104.294 Y3.136 E0.02000\n",
            ";C_SEAM_START\n",
            ";C seam travel: lift + direct\n",
            "G1 E-0.5 F1800\n",
            "G1 Y1.400 F12720 ;lift\n",
            "G1 X140.000 Y1.400 F12720 ;seam travel\n",
            "G1 Y1.000 F12720 ;lower\n",
            "G1 E0.45 F1800\n",
            "G1 F12720\n",
            "G1 X140.200 Y1.000 E0.02000\n",
            ";C_SEAM_START\n",
        ]
        # 32 ;LAYER_CHANGE markers so the pairs land on layer 32.
        text = ";LAYER_CHANGE\n" * 32 + "".join(lines)
        out, removed = topfix(text)
        self.assertEqual([p["layer"] for p in removed], [32])
        self.assertEqual(len(removed), 1)
        self.assertNotIn("G1 X104.294 Y3.436", "".join(
            ln for ln in out.splitlines() if "E-0.5" in ln or "E0.45" in ln
        ))
        self.assertIn("G1 E-0.5 F1800", out)
        self.assertEqual(out.count("G1 E-0.5 F1800"), 1)
        self.assertEqual(out.count("G1 F12720\n"), 1)

    def test_reslice_matches_printed_file(self) -> None:
        slicer = _slicer_bin()
        resources = _resources()
        stl = _ensure_stl()
        if slicer is None or resources is None or stl is None:
            self.skipTest("OrcaBelt def8eff480 binary, resources, or the round 2.5 mm STL is not available")
        summary = load_summary()
        work = Path(tempfile.mkdtemp(prefix="apexcore95a-"))
        try:
            dest = work / "apexcore_95a.gcode"
            run_pipeline(work, stl, dest)
            text = dest.read_text(errors="replace")
            got_events = retract_events(text)
            self.assertEqual(got_events, summary["events"], _event_diff(got_events, summary["events"]))
            got_features = feature_rows(text)
            for name, expect in summary["features"].items():
                self.assertIn(name, got_features, name)
                exp = expect["e_per_mm"]
                got = got_features[name]["e_per_mm"]
                if exp == 0:
                    self.assertEqual(got, 0.0)
                else:
                    self.assertLessEqual(abs(got - exp) / abs(exp), E_MM_TOL, f"{name} E/mm {got} vs {exp}")
            digest = hashlib.sha256(dest.read_bytes()).hexdigest()
            stamped = normalize_timestamp(text, summary["generated_by"])
            stamped_sha = hashlib.sha256(stamped.encode()).hexdigest()
            if digest == GOLDEN_SHA:
                self.assertEqual(digest, GOLDEN_SHA)
            self.assertEqual(
                stamped_sha,
                summary["sha256_timestamp_normalized"],
                f"raw sha256 {digest} (printed {GOLDEN_SHA})",
            )
        finally:
            shutil.rmtree(work, ignore_errors=True)


def _event_diff(got: list, expect: list, limit: int = 8) -> str:
    if got == expect:
        return ""
    lines = [f"events {len(got)} vs {len(expect)}"]
    n = min(len(got), len(expect))
    shown = 0
    for i in range(n):
        if got[i] != expect[i]:
            lines.append(f"  {i}: got {got[i]} expected {expect[i]}")
            shown += 1
            if shown >= limit:
                break
    if len(got) != len(expect) and shown < limit:
        lines.append(f"  length delta {len(got) - len(expect)}")
    return "\n".join(lines)


if __name__ == "__main__":
    unittest.main()
