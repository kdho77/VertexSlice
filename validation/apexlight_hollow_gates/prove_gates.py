#!/usr/bin/env python3
"""prove_gates.py — no-op and bad-change proofs. Frozen with this folder.

Synthetic proofs always run. They do not need a slicer.

  python3 validation/apexlight_hollow_gates/prove_gates.py

The live no-op runs when the main ApexLight and ApexCore slices are passed.
Live ApexLight must fail hollow, G1, and G2. Live compared with itself must
pass surface lock, filament, and ApexCore identity.

  python3 validation/apexlight_hollow_gates/prove_gates.py \
      --live-light /path/live_apex_light.gcode \
      --live-core /path/main_apex_core.gcode \
      --slice-seconds 158.672 \
      --json validation/apexlight_hollow_gates/proof/live_noop.json

Exit 0 only when every expected PASS/FAIL holds. Deliberate bad files are
written under /tmp and are not part of the freeze.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import ahg_common as C
import core_identity
import filament_delta
import g1_thin_bond
import g2_thick_bond
import hollow_tool
import slice_time
import surface_lock

A = math.pi * (0.875 ** 2)
CAP = C.H_CAP
HERE = os.path.dirname(os.path.abspath(__file__))


def e_of(length, width):
    return (width - CAP) * C.H_BEAD / A * length


def _footer(mm, grams):
    return [
        "; filament used [mm] = %.2f" % mm,
        "; filament used [g] = %.2f" % grams,
        "; total filament used [g] = %.2f" % grams,
        "G91",
    ]


def _file(layers, mm=100.0, grams=0.30, stamp="2026-11-24 at 00:00:00"):
    """layers maps the parser layer number (1-based forefoot) to move lines.

    The parser's first LAYER_CHANGE is layer 0, so one empty change is emitted
    before layer 1.
    """
    out = [
        "; generated by OrcaSlicer 2.3.2-dev on %s" % stamp,
        "; filament_diameter: 1.75",
        ";HEIGHT:0.46",
        "M83",
        "M104 S225",
        "M106 S127",
        "M204 S8000",
        ";LAYER_CHANGE",
        ";HEIGHT:0.46",
    ]
    last = max(layers) if layers else 1
    for layer in range(1, last + 1):
        out.append(";LAYER_CHANGE")
        out.append(";HEIGHT:0.46")
        out.extend(layers.get(layer, []))
    out.extend(_footer(mm, grams))
    return "\n".join(out) + "\n"


def _open_layer(x, y, layer):
    # Each layer lifts Z, so the layer-change travel is a real Z move.
    return ["G0 X%.3f Y%.3f Z%.3f F9000" % (x, y, 0.46 * layer)]


def _belt_loop(x0, x1, y0, y1, width, layer):
    """Closed outer wall. The seam starts on the belt edge (y0)."""
    return _open_layer(x0, y0, layer) + [
        ";TYPE:Outer wall",
        ";HEIGHT:0.46",
        "G1 X%.3f Y%.3f E%.5f F1500" % (x1, y0, e_of(x1 - x0, width)),
        "G1 X%.3f Y%.3f E%.5f" % (x1, y1, e_of(abs(y1 - y0), width)),
        "G1 X%.3f Y%.3f E%.5f" % (x0, y1, e_of(x1 - x0, width)),
        "G1 X%.3f Y%.3f E%.5f" % (x0, y0, e_of(abs(y1 - y0), width)),
    ]


def _dorsal_seam_loop(x0, x1, y0, y1, width, layer):
    """Same rectangle, seam and layer change parked on the dorsal edge."""
    return _open_layer(x0, y1, layer) + [
        ";TYPE:Outer wall",
        ";HEIGHT:0.46",
        "G1 X%.3f Y%.3f E%.5f F1500" % (x1, y1, e_of(x1 - x0, width)),
        "G1 X%.3f Y%.3f E%.5f" % (x1, y0, e_of(abs(y1 - y0), width)),
        "G1 X%.3f Y%.3f E%.5f" % (x0, y0, e_of(x1 - x0, width)),
        "G1 X%.3f Y%.3f E%.5f" % (x0, y1, e_of(abs(y1 - y0), width)),
    ]


def _infill(x0, x1, y, width):
    return [
        "G0 X%.3f Y%.3f F9000" % (x0, y),
        ";TYPE:Sparse infill",
        "G1 X%.3f Y%.3f E%.5f F1200" % (x1, y, e_of(x1 - x0, width)),
    ]


def _hollow_layers():
    """Layer 1 is a thin unbonded skin. Layer 2 is a >=3 mm hollow."""
    x0, x1 = 20.0, 80.0
    return {
        1: _belt_loop(x0, x1, 0.50, 2.40, 0.90, 1),
        2: _belt_loop(x0, x1, 0.50, 5.00, 1.00, 2),
    }


def _filled_layers():
    """Same walls as the hollow fixture. Sparse infill is added only in the gap."""
    layers = _hollow_layers()
    thick = list(layers[2])
    for y in (1.40, 2.50, 3.60, 4.40):
        thick.extend(_infill(20.0, 80.0, y, 1.40))
    layers[2] = thick
    return layers


def _write(directory, name, text):
    path = os.path.join(directory, name)
    open(path, "w").write(text)
    return path


def _check(rows, label, rep, expect):
    ok = rep["result"] == expect
    rows.append({
        "check": label,
        "expect": expect,
        "result": rep["result"],
        "ok": ok,
        "failures": rep.get("failures"),
        "detail": {k: rep[k] for k in rep if k not in ("failures", "columns", "examples_off_bottom")},
    })
    return ok


def synthetic(directory):
    rows = []
    ok = True
    hollow = _write(directory, "hollow.gcode", _file(_hollow_layers()))
    filled = _write(directory, "filled.gcode", _file(_filled_layers(), mm=140.0, grams=0.42))
    seam = _write(directory, "seam_top.gcode", _file({
        1: _hollow_layers()[1],
        2: _dorsal_seam_loop(20.0, 80.0, 0.50, 5.00, 1.00, 2),
    }))
    # Layer-change only: the Z travel ends on the dorsal edge, then a travel
    # returns to the live seam so the wall path itself does not move.
    lc_layers = _hollow_layers()
    lc_body = [
        "G0 X20.000 Y5.000 Z0.920 F9000",
        "G0 X20.000 Y0.500 F9000",
    ] + list(lc_layers[2])[1:]
    lc = _write(directory, "layer_change_top.gcode", _file({1: lc_layers[1], 2: lc_body}))
    wall_layers = _hollow_layers()
    wall_body = list(wall_layers[2])
    for i, line in enumerate(wall_body):
        if line.startswith("G1 ") and "X80.000" in line:
            wall_body[i] = line.replace("X80.000", "X80.300", 1)
            break
    wall = _write(directory, "wall_moved.gcode", _file({1: wall_layers[1], 2: wall_body}))
    poke_layers = _hollow_layers()
    poke_body = list(poke_layers[2]) + [
        "G0 X20.000 Y-2.000 F9000",
        ";TYPE:Sparse infill",
        "G1 X40.000 Y-2.000 E%.5f F1200" % e_of(20.0, 1.0),
    ]
    poke = _write(directory, "poke_outside.gcode", _file({1: poke_layers[1], 2: poke_body}, mm=110.0, grams=0.33))
    core = _write(directory, "core.gcode", _file(_hollow_layers(), stamp="2026-11-24 at 00:00:00"))
    core_stamp = _write(directory, "core_stamp.gcode", _file(_hollow_layers(), stamp="2026-11-24 at 01:02:03"))
    core_text = open(core).read().replace("G1 X80.000 Y0.500 E", "G1 X80.010 Y0.500 E", 1)
    core_bad = _write(directory, "core_bad.gcode", core_text)

    ok &= _check(rows, "hollow left on an empty >=3 mm section", hollow_tool.evaluate(hollow), "FAIL")
    ok &= _check(rows, "G1 unbonded thin section", g1_thin_bond.evaluate(hollow, hollow), "FAIL")
    ok &= _check(rows, "G2 unbonded thick section", g2_thick_bond.evaluate(hollow, hollow), "FAIL")
    ok &= _check(rows, "filled section clears hollow", hollow_tool.evaluate(filled), "PASS")
    ok &= _check(rows, "outer walls identical to themselves", surface_lock.evaluate(hollow, hollow), "PASS")
    ok &= _check(rows, "seam moved to the dorsal edge", surface_lock.evaluate(seam, hollow), "FAIL")
    ok &= _check(rows, "layer change moved off the bottom", surface_lock.evaluate(lc, hollow), "FAIL")
    ok &= _check(rows, "outer-wall path altered", surface_lock.evaluate(wall, hollow), "FAIL")
    ok &= _check(rows, "filament self", filament_delta.evaluate(hollow, hollow), "PASS")
    ok &= _check(rows, "extrusion outside the live outline", filament_delta.evaluate(poke, hollow), "FAIL")
    ok &= _check(rows, "slice time 158 s", slice_time.evaluate(158.672), "PASS")
    ok &= _check(rows, "slice time 176 s", slice_time.evaluate(176.059), "PASS")
    ok &= _check(rows, "slice time 261 s", slice_time.evaluate(261.0), "FAIL")
    ok &= _check(rows, "slice time missing", slice_time.evaluate(None), "FAIL")
    ok &= _check(rows, "ApexCore identical to itself", core_identity.evaluate(core, core), "PASS")
    ok &= _check(rows, "ApexCore stamp-only change", core_identity.evaluate(core_stamp, core), "PASS")
    ok &= _check(rows, "ApexCore motion byte changed", core_identity.evaluate(core_bad, core), "FAIL")
    # A candidate that only adds the fill, against the hollow file, must not move walls.
    ok &= _check(rows, "added fill keeps the outer wall", surface_lock.evaluate(filled, hollow), "PASS")
    return ok, rows


def live(light, core, seconds):
    rows = []
    ok = True
    h = hollow_tool.evaluate(light)
    g1 = g1_thin_bond.evaluate(light, light)
    g2 = g2_thick_bond.evaluate(light, light)
    surf = surface_lock.evaluate(light, light)
    fil = filament_delta.evaluate(light, light)
    tim = slice_time.evaluate(seconds)
    ident = core_identity.evaluate(core, core)
    core_h = hollow_tool.evaluate(core)
    ok &= _check(rows, "live ApexLight hollow is not 0", h, "FAIL")
    ok &= _check(rows, "live ApexLight G1 unbonded", g1, "FAIL")
    ok &= _check(rows, "live ApexLight G2 unbonded", g2, "FAIL")
    ok &= _check(rows, "live ApexLight walls identical to themselves", surf, "PASS")
    ok &= _check(rows, "live ApexLight filament self", fil, "PASS")
    ok &= _check(rows, "live slice time under 260 s", tim, "PASS")
    ok &= _check(rows, "ApexCore identical to itself", ident, "PASS")
    # Locked readings from the main slice this gate was frozen against.
    locks = []
    def lock(name, got, exp):
        good = got == exp
        locks.append({"lock": name, "got": got, "expect": exp, "ok": good})
        return good
    ok &= lock("G1 unbonded", g1["unbonded"], 14377)
    ok &= lock("G1 columns", g1["thin_columns"], 14813)
    ok &= lock("G2 unbonded", g2["unbonded"], 8648)
    ok &= lock("G2 columns", g2["thick_columns"], 9003)
    ok &= lock("G2 belt air pct", round(g2["belt_air_pct"], 1), 91.8)
    ok &= lock("G2 dorsal air pct", round(g2["dorsal_air_pct"], 1), 82.4)
    ok &= lock("ApexLight max air mm", round(h["max_air_mm"], 3), 11.633)
    ok &= lock("ApexLight forefoot hollow", h["forefoot_165"], 1387)
    ok &= lock("ApexLight total hollow", h["total"], 5683)
    ok &= lock("ApexLight physical last", h["physical_last"], 165)
    ok &= lock("ApexCore forefoot hollow", core_h["forefoot_165"], 0)
    rows.append({"check": "locked live readings", "ok": all(item["ok"] for item in locks), "locks": locks,
                 "apexlight_hollow": {k: h[k] for k in ("forefoot_165", "physical_count", "physical_last", "total", "max_air_mm", "above_165")},
                 "apexcore_hollow": {k: core_h[k] for k in ("forefoot_165", "physical_count", "total", "max_air_mm", "above_165")},
                 "filament": {k: fil[k] for k in ("live_filament_mm", "live_filament_g", "result")}})
    # A bad byte in a copy of the live core is rejected, and a wall edit is rejected.
    bad_core = light + ".core-bad-proof"
    # Use a temp sibling of the core file.
    return ok, rows, h, g1, g2


def live_bad(light, core, directory):
    rows = []
    ok = True
    text = open(core, "rb").read()
    # Flip a motion byte well past the stamp line.
    idx = text.find(b"\nG1 ")
    if idx < 0:
        rows.append({"check": "found a G1 to corrupt", "ok": False})
        return False, rows
    flipped = bytearray(text)
    flipped[idx + 4] = flipped[idx + 4] ^ 0x01
    bad = _write(directory, "live_core_byte.gcode", flipped.decode("utf-8", "replace"))
    ok &= _check(rows, "bad change of a live ApexCore byte", core_identity.evaluate(bad, core), "FAIL")
    # Move one outer-wall coordinate in a copy of live ApexLight.
    src = open(light, errors="replace").read()
    needle = "\n;TYPE:Outer wall\n"
    at = src.find(needle)
    g1 = src.find("\nG1 ", at)
    if g1 < 0:
        rows.append({"check": "found an outer wall", "ok": False})
        return False, rows
    # Nudge the first X value on that G1.
    line_end = src.find("\n", g1 + 1)
    line = src[g1 + 1:line_end]
    if "X" not in line:
        rows.append({"check": "outer wall line has X", "ok": False, "line": line})
        return False, rows
    nudged = line.replace("X", "X", 1)
    # Add 0.2 mm to the first X number.
    import re
    def bump(m):
        return "X%.3f" % (float(m.group(1)) + 0.2)
    new_line, n = re.subn(r"X([0-9.]+)", bump, line, count=1)
    if n != 1:
        rows.append({"check": "bumped an X", "ok": False})
        return False, rows
    edited = src[:g1 + 1] + new_line + src[line_end:]
    wall = _write(directory, "live_wall_moved.gcode", edited)
    ok &= _check(rows, "bad change of a live outer-wall path", surface_lock.evaluate(wall, light), "FAIL")
    return ok, rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--live-light")
    ap.add_argument("--live-core")
    ap.add_argument("--slice-seconds", type=float)
    ap.add_argument("--json")
    a = ap.parse_args()
    work = tempfile.mkdtemp(prefix="ahg_proof_")
    syn_ok, syn_rows = synthetic(work)
    report = {"synthetic_ok": syn_ok, "synthetic": syn_rows}
    all_ok = syn_ok
    if a.live_light or a.live_core:
        if not (a.live_light and a.live_core and a.slice_seconds is not None):
            raise SystemExit("live proof needs --live-light, --live-core, and --slice-seconds")
        live_ok, live_rows, _h, _g1, _g2 = live(a.live_light, a.live_core, a.slice_seconds)
        bad_ok, bad_rows = live_bad(a.live_light, a.live_core, work)
        report["live_ok"] = live_ok and bad_ok
        report["live"] = live_rows
        report["live_bad"] = bad_rows
        all_ok = all_ok and live_ok and bad_ok
    report["result"] = "PASS" if all_ok else "FAIL"
    text = json.dumps(C.round_report(report), indent=1) + "\n"
    if a.json:
        os.makedirs(os.path.dirname(os.path.abspath(a.json)), exist_ok=True)
        open(a.json, "w").write(text)
    print(text)
    sys.exit(0 if all_ok else 1)


if __name__ == "__main__":
    main()
