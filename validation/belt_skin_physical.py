#!/usr/bin/env python3
"""Independent toe-skin gate. Widths come from E, not from ;WIDTH comments.

Raster is 0.05 mm. A column's bead edges are E * filament_area / (length * layer_height).
The slice-proof job fails when any limit below fails. The hairline fill on PR #36
fails width, feed, the outer-wall split, and the air cap; the tests lock that.
"""
from __future__ import annotations

import json
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

WORD = re.compile(r"([XYZEF])\s*(-?(?:\d+\.?\d*|\.\d+))", re.IGNORECASE)
GENERATED = re.compile(r"^;\s*generated by\b", re.IGNORECASE)
KEY_NUM = re.compile(r"^;\s*([A-Za-z0-9_]+)\s*=\s*([0-9.]+)", re.M)

MIN_WIDTH = 0.45
MAX_WIDTH = 1.6
MIN_LEN = 0.1
AIR_CAP = 0.5
COLUMN_CAP = 0.2
RASTER = 0.05
TOUCH = 0.02
MAX_THICK = 5.0
TIME_FRAC = 0.01
FILAMENT_FRAC = 0.03


def _body(line: str) -> str:
    return line.split(";", 1)[0].strip()


def _words(line: str) -> dict[str, float]:
    return {m.group(1).upper(): float(m.group(2)) for m in WORD.finditer(_body(line))}


def _num(text: str, key: str, default: float) -> float:
    for match in KEY_NUM.finditer(text):
        if match.group(1) == key:
            return float(match.group(2))
    return default


def _footer(text: str, prefix: str) -> float | None:
    for line in text.splitlines():
        if line.startswith(prefix):
            tail = line.split("=", 1)[-1].strip()
            match = re.search(r"[0-9.]+", tail)
            return float(match.group(0)) if match else None
    return None


def _time_seconds(text: str) -> float | None:
    for line in text.splitlines():
        if line.startswith("; estimated printing time"):
            match = re.search(r"(?:(\d+)h)?\s*(?:(\d+)m)?\s*(?:(\d+)s)?", line.split("=", 1)[-1])
            if not match:
                return None
            h, m, s = (int(match.group(i) or 0) for i in (1, 2, 3))
            return h * 3600 + m * 60 + s
    return None


def parse_moves(text: str) -> dict:
    """Extrusions with E-derived width, travels, retracts, seams, kinematics."""
    lh = _num(text, "layer_height", 0.46)
    dia = _num(text, "filament_diameter", 1.75)
    if dia <= 0.0:
        # The header sometimes uses "filament_diameter: 1.75".
        match = re.search(r"filament_diameter\s*[:=]\s*([0-9.]+)", text)
        dia = float(match.group(1)) if match else 1.75
    area = math.pi * (dia / 2.0) ** 2
    gap_v = _num(text, "gap_infill_speed", 26.0)
    solid_v = _num(text, "internal_solid_infill_speed", gap_v)
    machine_v = min(_num(text, "machine_max_speed_x", 500.0), _num(text, "machine_max_speed_y", 500.0))
    accel_xy = min(
        _num(text, "machine_max_acceleration_x", 5000.0),
        _num(text, "machine_max_acceleration_y", 5000.0),
    )
    accel_ext = min(accel_xy, _num(text, "machine_max_acceleration_extruding", accel_xy))
    accel_travel = min(accel_xy, _num(text, "machine_max_acceleration_travel", accel_xy))
    rcw = _num(text, "reduce_crossing_wall", -1.0)

    layers: list[dict] = []
    current: dict | None = None
    role = ""
    x = y = None
    feed = 0.0
    relative = True
    retracts = 0
    seams: list[tuple[float, float]] = []
    moves: list[tuple[float, float, bool, float, float]] = []
    positive_e = 0.0

    for raw in text.splitlines():
        if "seam" in raw.lower():
            words = _words(raw)
            if "X" in words and "Y" in words:
                seams.append((round(words["X"], 3), round(words["Y"], 3)))
        line = raw.strip()
        if line.startswith(";TYPE:"):
            role = line.split(":", 1)[1].strip()
            continue
        if line.startswith(";LAYER_CHANGE"):
            current = None
            continue
        if line.startswith(";Z:"):
            try:
                z = float(line.split(":", 1)[1])
            except ValueError:
                continue
            current = {"z": z, "segs": []}
            layers.append(current)
            continue
        body = _body(line)
        if body.startswith("M83"):
            relative = True
            continue
        if body.startswith("M82"):
            relative = False
            continue
        if not (body.startswith("G0") or body.startswith("G1")):
            continue
        words = _words(line)
        if "F" in words:
            feed = words["F"]
        nx = words.get("X", x)
        ny = words.get("Y", y)
        de = 0.0
        if "E" in words:
            de = words["E"] if relative else 0.0
            if words["E"] < -1e-9:
                retracts += 1
            if relative and words["E"] > 0.0:
                positive_e += words["E"]
        if x is None or y is None or nx is None or ny is None:
            if nx is not None:
                x, y = nx, ny
            continue
        dist = math.hypot(nx - x, ny - y)
        extrude = de > 1e-9 and dist > 1e-9
        if dist > 1e-9:
            moves.append((dist, feed / 60.0, extrude, nx - x, ny - y))
        if extrude and current is not None:
            width = de * area / (dist * lh) if lh > 0.0 else 0.0
            current["segs"].append((x, y, nx, ny, width, role, feed / 60.0, dist, de))
        x, y = nx, ny

    return {
        "layers": [layer for layer in layers if layer.get("z") is not None],
        "moves": moves,
        "retracts": retracts,
        "seams": seams,
        "positive_e": positive_e,
        "lh": lh,
        "area": area,
        "feed_cap": min(gap_v, solid_v, machine_v),
        "machine_v": machine_v,
        "accel_ext": accel_ext,
        "accel_travel": accel_travel,
        "rcw": rcw,
        "footer_mm": _footer(text, "; filament used [mm]"),
        "footer_g": _footer(text, "; filament used [g]"),
        "footer_total_g": _footer(text, "; total filament used [g]"),
        "footer_cm3": _footer(text, "; filament used [cm3]"),
        "footer_time": _time_seconds(text),
    }


def _band(z: float, z0: float, z1: float) -> str | None:
    span = z1 - z0
    frac = 0.0 if span <= 1e-9 else (z - z0) / span
    # Inclusive. The layer whose fraction rounds onto 0.30 is still in the band.
    if frac < -1e-9 or frac > 0.30 + 1e-4:
        return None
    if frac <= 0.15:
        return "0-15"
    return "15-30"


def _air(layers: list[dict], lh: float) -> dict:
    zs = [layer["z"] for layer in layers]
    z0 = min(zs) if zs else 0.0
    z1 = max(zs) if zs else 0.0
    bands = {
        name: {"air_mm3": 0.0, "columns": 0, "worst_mm": 0.0, "over_0_2": 0}
        for name in ("0-15", "15-30")
    }
    for layer in layers:
        band = _band(layer["z"], z0, z1)
        if band is None or not layer["segs"]:
            continue
        bins: dict[int, list] = defaultdict(list)
        xs: list[float] = []
        for seg in layer["segs"]:
            xs.extend((seg[0], seg[2]))
            lo, hi = min(seg[0], seg[2]), max(seg[0], seg[2])
            for key in range(int(math.floor(lo)), int(math.floor(hi)) + 1):
                bins[key].append(seg)
        for index in range(int(math.floor(min(xs) / RASTER)), int(math.ceil(max(xs) / RASTER)) + 1):
            x = index * RASTER
            intervals = []
            for seg in bins.get(int(math.floor(x)), ()):
                span = seg[2] - seg[0]
                if abs(span) < 1e-9:
                    continue
                t = (x - seg[0]) / span
                if t < 0.0 or t > 1.0:
                    continue
                yy = seg[1] + t * (seg[3] - seg[1])
                half = seg[4] / 2.0
                intervals.append((yy - half, yy + half))
            if len(intervals) < 2:
                continue
            intervals.sort()
            merged = [list(intervals[0])]
            for lo, hi in intervals[1:]:
                if lo <= merged[-1][1] + TOUCH:
                    merged[-1][1] = max(merged[-1][1], hi)
                else:
                    merged.append([lo, hi])
            if merged[-1][1] - merged[0][0] > MAX_THICK:
                continue
            for left, right in zip(merged, merged[1:]):
                gap = right[0] - left[1]
                if gap <= TOUCH:
                    continue
                bands[band]["air_mm3"] += gap * RASTER * lh
                bands[band]["columns"] += 1
                if gap > bands[band]["worst_mm"]:
                    bands[band]["worst_mm"] = gap
                if gap > COLUMN_CAP:
                    bands[band]["over_0_2"] += 1
    for band in bands.values():
        band["air_mm3"] = round(band["air_mm3"], 2)
        band["worst_mm"] = round(band["worst_mm"], 3)
    return bands


def _replay(moves: list[tuple[float, float, bool, float, float]], accel_ext: float, accel_travel: float, machine_v: float) -> float:
    """Trapezoid from the previous corner speed. Commanded feed is capped at the machine max."""
    total = 0.0
    speed = 0.0
    prev_dx = prev_dy = None
    for dist, feed, extrude, dx, dy in moves:
        cruise = min(max(feed, 0.0), machine_v)
        accel = accel_ext if extrude else accel_travel
        if accel <= 1.0 or dist <= 1e-9:
            continue
        if prev_dx is not None:
            dot = prev_dx * dx + prev_dy * dy
            denom = math.hypot(prev_dx, prev_dy) * math.hypot(dx, dy)
            cosine = dot / denom if denom > 1e-12 else 1.0
            # A sharp corner drops the entry speed. A straight line keeps it.
            if cosine < 0.95:
                speed = min(speed, cruise * max(0.0, cosine))
        entry = min(speed, cruise)
        accel_dist = max(0.0, (cruise * cruise - entry * entry) / (2.0 * accel))
        if accel_dist >= dist:
            peak = math.sqrt(max(0.0, entry * entry + 2.0 * accel * dist))
            total += (peak - entry) / accel
            speed = peak
        else:
            total += (cruise - entry) / accel + (dist - accel_dist) / cruise
            speed = cruise
        prev_dx, prev_dy = dx, dy
    return total


def _key(seg: tuple) -> tuple:
    return (
        round(seg[0], 3),
        round(seg[1], 3),
        round(seg[2], 3),
        round(seg[3], 3),
        seg[5],
    )


def _outer_grid(outers: list[tuple]) -> dict[tuple[int, int], list]:
    grid: dict[tuple[int, int], list] = defaultdict(list)
    for seg in outers:
        x0, x1 = sorted((seg[0], seg[2]))
        y0, y1 = sorted((seg[1], seg[3]))
        for ix in range(int(math.floor(x0)), int(math.floor(x1)) + 1):
            for iy in range(int(math.floor(y0)), int(math.floor(y1)) + 1):
                grid[(ix, iy)].append(seg)
    return grid


def _near_outer(point: tuple[float, float], grid: dict[tuple[int, int], list]) -> bool:
    px, py = point
    ix, iy = int(math.floor(px)), int(math.floor(py))
    seen: set[int] = set()
    for dx in (-1, 0, 1):
        for dy in (-1, 0, 1):
            for seg in grid.get((ix + dx, iy + dy), ()):
                ident = id(seg)
                if ident in seen:
                    continue
                seen.add(ident)
                vx, vy = seg[2] - seg[0], seg[3] - seg[1]
                length2 = vx * vx + vy * vy
                if length2 < 1e-12:
                    dist = math.hypot(px - seg[0], py - seg[1])
                else:
                    t = max(0.0, min(1.0, ((px - seg[0]) * vx + (py - seg[1]) * vy) / length2))
                    dist = math.hypot(px - (seg[0] + t * vx), py - (seg[1] + t * vy))
                if dist <= 0.05:
                    return True
    return False


def _outer_edge(layers: list[dict]) -> dict[tuple[float, float], tuple[float, float]]:
    """(layer z, x) -> (lowest outer edge, highest outer edge), from E-derived width."""
    edges = {}
    for layer in layers:
        outers = [seg for seg in layer["segs"] if seg[5].startswith("Outer")]
        if not outers:
            continue
        xs = [p for seg in outers for p in (seg[0], seg[2])]
        x = min(xs)
        z = round(layer["z"], 3)
        while x <= max(xs) + 1e-6:
            ys = []
            for seg in outers:
                span = seg[2] - seg[0]
                if abs(span) < 1e-9:
                    continue
                t = (x - seg[0]) / span
                if t < 0.0 or t > 1.0:
                    continue
                yy = seg[1] + t * (seg[3] - seg[1])
                ys.append(yy - seg[4] / 2.0)
                ys.append(yy + seg[4] / 2.0)
            if ys:
                edges[(z, round(x, 2))] = (min(ys), max(ys))
            x += 0.5
    return edges


def _buckets(segs: list[tuple]) -> dict:
    width = {"<0.45": 0, "0.45-0.8": 0, "0.8-1.2": 0, "1.2-1.6": 0, ">1.6": 0}
    speed = {"<=26": 0, "26-100": 0, "100-500": 0, ">500": 0}
    for seg in segs:
        w, v = seg[4], seg[6]
        if w < MIN_WIDTH:
            width["<0.45"] += 1
        elif w < 0.8:
            width["0.45-0.8"] += 1
        elif w < 1.2:
            width["0.8-1.2"] += 1
        elif w <= MAX_WIDTH + 1e-3:
            width["1.2-1.6"] += 1
        else:
            width[">1.6"] += 1
        if v <= 26.0 + 1e-6:
            speed["<=26"] += 1
        elif v <= 100.0:
            speed["26-100"] += 1
        elif v <= 500.0:
            speed["100-500"] += 1
        else:
            speed[">500"] += 1
    return {"width": width, "speed_mm_s": speed, "count": len(segs)}


def _crossings(text: str) -> dict:
    here = Path(__file__).resolve().parents[1] / "scripts" / "g2b_heelmod"
    if str(here) not in sys.path:
        sys.path.insert(0, str(here))
    from check_travel_wall_crossings import analyze

    report = analyze(text)
    per = {}
    for row in report.get("layers_with_crossings", []):
        per[round(row["z"], 3)] = {
            "perimeter": row.get("perimeter_crossings", 0),
            "outer": row.get("outer_only_crossings", 0),
        }
    totals = report["totals"]
    return {
        "perimeter": totals.get("perimeter_crossings", 0),
        "outer": totals.get("outer_only_crossings", 0),
        "skin_interior_travels": totals.get("skin_interior_travels", 0),
        "per_layer": per,
    }


def _published_grams(text: str) -> float | None:
    match = re.search(r'filament_settings_id\s*=\s*"?([^"\n]+)', text)
    if match is None:
        return None
    name = match.group(1)
    if "ApexCore" in name and "Forge" not in name:
        return 84.05
    if "ApexLight" in name and "Forge" not in name and "Bounce" not in name:
        return 75.70
    return None


def audit_texts(live_text: str, new_text: str) -> dict:
    live = parse_moves(live_text)
    new = parse_moves(new_text)
    live_map = {_key(seg): seg for layer in live["layers"] for seg in layer["segs"]}
    added = []
    changed = []
    for layer in new["layers"]:
        for seg in layer["segs"]:
            old = live_map.get(_key(seg))
            if old is None:
                added.append(seg)
            elif abs(old[8] - seg[8]) > 1e-4 or abs(old[6] - seg[6]) > 1e-3:
                changed.append(seg)
    touched = added + changed
    outers = [seg for layer in live["layers"] for seg in layer["segs"] if seg[5].startswith("Outer")]
    outer_grid = _outer_grid(outers)

    narrow = [seg for seg in touched if seg[4] < MIN_WIDTH - 1e-3]
    wide = [seg for seg in touched if seg[4] > MAX_WIDTH + 1e-3]
    fast = [seg for seg in touched if seg[6] > new["feed_cap"] + 1e-3]
    short = [seg for seg in added if seg[7] < MIN_LEN - 1e-6]
    on_outer = [
        seg
        for seg in added
        if _near_outer((seg[0], seg[1]), outer_grid) or _near_outer((seg[2], seg[3]), outer_grid)
    ]

    live_air = _air(live["layers"], live["lh"])
    new_air = _air(new["layers"], new["lh"])
    air_fail = []
    for name, band in new_air.items():
        if band["air_mm3"] > AIR_CAP or band["worst_mm"] > COLUMN_CAP:
            air_fail.append(f"{name} {band['air_mm3']} mm3 worst {band['worst_mm']} over0.2={band['over_0_2']}")

    live_time = _replay(live["moves"], live["accel_ext"], live["accel_travel"], live["machine_v"])
    new_time = _replay(new["moves"], new["accel_ext"], new["accel_travel"], new["machine_v"])
    time_cap = live_time * (1.0 + TIME_FRAC)
    # Filament cap is against the published live grams when this file is one of
    # those two materials. The paired slice can already sit above that live file.
    published = _published_grams(live_text)
    live_grams = published if published is not None else live["footer_g"]

    def grams(mm: float | None) -> float | None:
        if mm is None or live["footer_mm"] in (None, 0.0):
            return None
        if live["footer_g"] is None:
            return None
        return mm * live["footer_g"] / live["footer_mm"]

    fil_cap = None if live_grams is None else live_grams * (1.0 + FILAMENT_FRAC)
    footer_consistent = True
    notes = []
    if new["footer_mm"] is not None and live["footer_mm"] is not None:
        expected = live["footer_mm"] + (new["positive_e"] - live["positive_e"])
        if abs(new["footer_mm"] - expected) > 1.0:
            footer_consistent = False
            notes.append(f"filament mm footer {new['footer_mm']} != extruded {expected:.2f}")
    if new["footer_g"] is not None and new["footer_total_g"] is not None:
        if abs(new["footer_g"] - new["footer_total_g"]) > 0.02:
            footer_consistent = False
            notes.append("total filament used [g] disagrees with filament used [g]")
    elif new["footer_total_g"] is None and live["footer_total_g"] is not None:
        footer_consistent = False
        notes.append("total filament used [g] missing")

    live_edge = _outer_edge(live["layers"])
    new_edge = _outer_edge(new["layers"])
    edge_dev = 0.0
    for key, pair in live_edge.items():
        other = new_edge.get(key)
        if other is None:
            edge_dev = max(edge_dev, 1.0)
            continue
        edge_dev = max(edge_dev, abs(pair[0] - other[0]), abs(pair[1] - other[1]))
    seams_ok = live["seams"] == new["seams"]

    live_over = sum(1 for layer in live["layers"] for seg in layer["segs"] if seg[4] > MAX_WIDTH + 1e-3)
    new_over = sum(1 for layer in new["layers"] for seg in layer["segs"] if seg[4] > MAX_WIDTH + 1e-3)

    live_travel = sum(dist for dist, _f, extrude, _dx, _dy in live["moves"] if not extrude)
    new_travel = sum(dist for dist, _f, extrude, _dx, _dy in new["moves"] if not extrude)

    try:
        live_x = _crossings(live_text)
        new_x = _crossings(new_text)
        cross_ok = new_x["perimeter"] <= live_x["perimeter"] and new_x["outer"] <= live_x["outer"]
        for z, row in new_x["per_layer"].items():
            old = live_x["per_layer"].get(z, {"perimeter": 0, "outer": 0})
            if row["perimeter"] > old["perimeter"] or row["outer"] > old["outer"]:
                cross_ok = False
        cross_detail = {
            "live_perimeter": live_x["perimeter"],
            "new_perimeter": new_x["perimeter"],
            "live_outer": live_x["outer"],
            "new_outer": new_x["outer"],
            "live_skin_interior_travels": live_x["skin_interior_travels"],
            "new_skin_interior_travels": new_x["skin_interior_travels"],
        }
    except Exception as exc:  # noqa: BLE001 — report the checker failure instead of hiding it
        cross_ok = False
        cross_detail = {"error": str(exc)}

    identical = _identity(live_text) == _identity(new_text)
    limits = {
        "1_width": {
            "ok": not narrow and not wide,
            "detail": f"added_or_changed={len(touched)} under_0.45={len(narrow)} over_1.6={len(wide)}",
        },
        "2_feed": {
            "ok": not fast,
            "detail": f"cap_mm_s={new['feed_cap']} over_cap={len(fast)}",
        },
        "3_outer_wall": {
            "ok": not on_outer and edge_dev <= 1e-3 and seams_ok,
            "detail": (
                f"added_on_outer={len(on_outer)} edge_dev_mm={edge_dev:.4f} "
                f"seams {len(new['seams'])}/{len(live['seams'])} match={seams_ok}"
            ),
        },
        "4_air": {
            "ok": not air_fail,
            "live": live_air,
            "new": new_air,
            "detail": "; ".join(air_fail) if air_fail else "within cap",
        },
        "5_time_filament": {
            "ok": new_time <= time_cap + 1e-6
            and (fil_cap is None or (new["footer_g"] or 0.0) <= fil_cap + 1e-6)
            and footer_consistent,
            "detail": (
                f"replay_s {live_time:.1f} -> {new_time:.1f} cap {time_cap:.1f}; "
                f"filament_g {live['footer_g']} -> {new['footer_g']} cap {None if fil_cap is None else round(fil_cap, 2)}; "
                + ("; ".join(notes) if notes else "footer consistent")
            ),
        },
        "6_travel_crossings": {
            "ok": new_travel <= live_travel + 0.05
            and cross_ok
            and new["rcw"] == 1
            and live["rcw"] == 1
            and new["retracts"] <= live["retracts"]
            and not short
            and new_over <= live_over,
            "detail": (
                f"travel {live_travel:.1f} -> {new_travel:.1f}; rcw {new['rcw']}; "
                f"retracts {live['retracts']} -> {new['retracts']}; "
                f"fragments={len(short)}; beads>1.6 {live_over} -> {new_over}; {cross_detail}"
            ),
        },
        "7_gcode_changed": {
            "ok": not identical,
            "detail": "identical to the unbonded slice" if identical else "gcode differs",
        },
    }
    return {
        "ok": all(row["ok"] for row in limits.values()),
        "limits": limits,
        "added_segments": _buckets(added),
        "changed_segments": _buckets(changed),
        "replay_s": {"live": round(live_time, 1), "new": round(new_time, 1)},
    }


def _identity(text: str) -> str:
    kept = [line for line in text.splitlines() if not GENERATED.match(line.strip())]
    return "\n".join(kept)


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: belt_skin_physical.py LIVE.gcode NEW.gcode")
    report = audit_texts(Path(sys.argv[1]).read_text(errors="replace"), Path(sys.argv[2]).read_text(errors="replace"))
    print(json.dumps(report, indent=2))
    if not report["ok"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
