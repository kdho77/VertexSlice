#!/usr/bin/env python3
"""prove_gates.py — Phase A evidence for the frozen forefoot gates.

Builds a synthetic inside-only widening fixture and, when the BASE ApexCore
slice is available, the no-op and the deliberate bad edits. Writes
proof/phase_a.json. Exit 0 only when every expected PASS/FAIL holds.

The synthetic fixture is the pass case. Real BASE is the no-op fail case.
Real BASE is not committed; pass --base-ortho (default /tmp/fcg_art/...).
"""
from __future__ import annotations

import argparse, json, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fcg_common as C
import g1_thin_bond, g2_thick_bond, g3_outer_edge, g4_seams
import g5_outside_scope, g6_flow, g7_time, g8_crossings, g9_filament_outline

HERE = os.path.dirname(os.path.abspath(__file__))
FIX = os.path.join(HERE, "fixtures")
A = math.pi * (0.875 ** 2)
CAP = C.H_CAP


def e_of(length, width):
    return (width - CAP) * C.H_BEAD / A * length


def _loop(x0, x1, y0, y1, feed):
    """CCW rectangle. y0 is the plantar centre, y1 the dorsal centre. Sides are width 1.0."""
    lines = ["G0 X%.3f Y%.3f F9000" % (x0, y0), ";TYPE:Outer wall", ";HEIGHT:0.46"]
    lines.append("G1 X%.3f Y%.3f E%.5f F%d" % (x1, y0, e_of(x1 - x0, (y0 - 0.0) * 2), feed))
    lines.append("G1 Y%.3f E%.5f" % (y1, e_of(y1 - y0, 1.0)))
    lines.append("G1 X%.3f E%.5f" % (x0, e_of(x1 - x0, (2.44 - y1) * 2 if y1 < 3 else (5.0 - y1) * 2)))
    lines.append("G1 Y%.3f E%.5f" % (y0, e_of(y1 - y0, 1.0)))
    return lines


def _file(body_by_layer, tail):
    out = ["; generated by OrcaSlicer 2.3.2-dev on 2026-11-21 at 00:00:00",
           "; filament_diameter: 1.75", ";HEIGHT:0.46", "M83", "M104 S225", "M106 S127", "M204 S8000"]
    for layer in range(0, 167):
        out.append(";LAYER_CHANGE")
        out.append(";HEIGHT:0.46")
        out.extend(body_by_layer.get(layer, []))
    out.extend(tail)
    out.append("G91")
    out.append("; estimated printing time (normal mode) = 1m 0s")
    return "\n".join(out) + "\n"


def write_synthetic(directory):
    os.makedirs(directory, exist_ok=True)
    # Thin layer 2. Outer edge fixed: plantar Y=0, dorsal Y=2.44.
    # Base centres 0.600 / 1.840 (width 1.20), gap +0.04 mm.
    # Cand centres 0.645 / 1.795 (width 1.29), overlap 0.14 mm. Centre shift 0.045 mm.
    # Thick layer 3. Skins identical. Base inner misses the skins; cand inner overlaps both by 0.35 mm.
    x0, x1 = 20.0, 220.0
    base_layers = {
        2: _loop(x0, x1, 0.600, 1.840, 1500),
        3: _loop(x0, x1, 0.575, 4.425, 1500) + [
            "G0 X20.000 Y2.500 F9000", ";TYPE:Inner wall",
            "G1 X220.000 E%.5f F480" % e_of(200.0, 1.15),
        ],
    }
    cand_layers = {
        2: _loop(x0, x1, 0.645, 1.795, 1500),
        3: _loop(x0, x1, 0.575, 4.425, 1500) + [
            "G0 X20.000 Y2.500 F9000", ";TYPE:Inner wall",
            "G1 X220.000 E%.5f F480" % e_of(200.0, 3.40),
        ],
    }
    tail = [";TYPE:Outer wall", "G1 X30.000 Y1.000 E0.20000 F1500"]
    paths = {}
    for name, layers in (("base", base_layers), ("cand", cand_layers)):
        path = os.path.join(directory, "synthetic_%s.gcode" % name)
        open(path, "w").write(_file(layers, tail))
        paths[name] = path
    stub = "; generated by OrcaSlicer 2.3.2-dev on 2026-11-21 at 00:00:00\n; material stub\nG1 X0 Y0 F1000\n"
    for label in ("light", "forge", "bounce"):
        path = os.path.join(directory, "synthetic_%s.gcode" % label)
        open(path, "w").write(stub)
        paths[label] = path
    return paths


def _expect(label, result, want, failures):
    ok = result == want
    failures.append(None if ok else "%s: got %s, expected %s" % (label, result, want))
    return {"label": label, "result": result, "expected": want, "ok": ok}


def grade_synthetic(paths):
    base, cand = paths["base"], paths["cand"]
    rows = []
    notes = []
    checks = [
        ("G1 base (gap, no-op)", g1_thin_bond.evaluate(base, base, "orthocad"), "FAIL"),
        ("G1 cand (inside-only widen)", g1_thin_bond.evaluate(cand, base, "orthocad"), "PASS"),
        ("G2 base", g2_thick_bond.evaluate(base, base, "orthocad"), "FAIL"),
        ("G2 cand", g2_thick_bond.evaluate(cand, base, "orthocad"), "PASS"),
        ("G3 cand", g3_outer_edge.evaluate(cand, base, "orthocad"), "PASS"),
        ("G4 cand", g4_seams.evaluate(cand, base, "orthocad"), "PASS"),
        ("G6 cand", g6_flow.evaluate(cand, "orthocad"), "PASS"),
        ("G7 cand", g7_time.evaluate(cand, base), "PASS"),
        ("G8 cand", g8_crossings.evaluate(cand, base), "PASS"),
        ("G9 cand", g9_filament_outline.evaluate(cand, base, "orthocad"), "PASS"),
    ]
    work = "/tmp/fcg_syn_bad"
    os.makedirs(work, exist_ok=True)
    # Outer wall moved 0.1 mm inward: plantar centre +0.1, dorsal centre -0.1, E unchanged.
    inward = os.path.join(work, "synthetic_inward.gcode")
    open(inward, "w").write(open(cand).read().replace("Y0.645", "Y0.745").replace("Y1.795", "Y1.695"))
    checks.append(("G3 inward 0.1", g3_outer_edge.evaluate(inward, base, "orthocad"), "FAIL"))
    # Seam moved to the top: the loop start Y becomes the dorsal centre.
    topped = os.path.join(work, "synthetic_seam_top.gcode")
    _move_starts_to_top(cand, topped)
    checks.append(("G4 seam to top", g4_seams.evaluate(topped, base, "orthocad"), "FAIL"))
    # Post-forefoot byte change.
    flipped = os.path.join(work, "synthetic_post.gcode")
    text = open(cand).read().replace("G1 X30.000 Y1.000 E0.20000 F1500", "G1 X31.000 Y1.000 E0.20000 F1500", 1)
    open(flipped, "w").write(text)
    g5 = g5_outside_scope.evaluate([("orthocad", base, flipped)],
                                   [("ApexLight", paths["light"], paths["light"]),
                                    ("ApexForge", paths["forge"], paths["forge"]),
                                    ("ApexBounce", paths["bounce"], paths["bounce"])], False)
    checks.append(("G5 post-forefoot byte", g5, "FAIL"))
    g5_ok = g5_outside_scope.evaluate([("orthocad", base, cand)],
                                      [("ApexLight", paths["light"], paths["light"]),
                                       ("ApexForge", paths["forge"], paths["forge"]),
                                       ("ApexBounce", paths["bounce"], paths["bounce"])], True)
    checks.append(("G5 cand + light/forge/bounce", g5_ok, "PASS"))
    # Flow over the cap.
    fast = os.path.join(work, "synthetic_fast.gcode")
    open(fast, "w").write(open(cand).read().replace("F1500", "F9000", 1))
    checks.append(("G6 over 35", g6_flow.evaluate(fast, "orthocad"), "FAIL"))
    # Time over +2%.
    slow = os.path.join(work, "synthetic_slow.gcode")
    open(slow, "w").write(open(cand).read().replace("F1500", "F100", 1))
    checks.append(("G7 over +2%", g7_time.evaluate(slow, base), "FAIL"))
    # A travel that crosses the rectangle.
    cross = os.path.join(work, "synthetic_cross.gcode")
    open(cross, "w").write(open(cand).read().replace(
        ";LAYER_CHANGE\n;HEIGHT:0.46\nG0 X20.000 Y0.645",
        ";LAYER_CHANGE\n;HEIGHT:0.46\nG0 X0 Y1.2 F9000\nG0 X240 Y1.2\nG0 X20.000 Y0.645", 1))
    checks.append(("G8 crossing", g8_crossings.evaluate(cross, base), "FAIL"))
    # Bead pushed outside the outline.
    poked = os.path.join(work, "synthetic_poke.gcode")
    _poke_outward(cand, poked)
    checks.append(("G9 outside outline", g9_filament_outline.evaluate(poked, base, "orthocad"), "FAIL"))

    report_rows = []
    bad = []
    for label, rep, want in checks:
        row = _expect(label, rep["result"], want, bad)
        row["failures"] = rep.get("failures", [])
        keep = {k: rep.get(k) for k in ("median_gap_mm", "unbonded", "belt_air_pct", "dorsal_air_pct",
                                        "p99_mm", "max_mm", "max_mm3_s", "increase_mm", "delta_pct",
                                        "closed_off_bottom", "starts_moved") if k in rep}
        row["measured"] = C.round_report(keep)
        report_rows.append(row)
        notes.append("%s -> %s (expected %s)" % (label, rep["result"], want))
    return {"rows": report_rows, "ok": not any(x is not None for x in bad),
            "problems": [x for x in bad if x]}, notes


def _move_starts_to_top(src, dst):
    """Move the first Outer-wall positioning Y on layers 2 and 3 up to the dorsal bead."""
    text = open(src).read()
    text = text.replace("G0 X20.000 Y0.645 F9000", "G0 X20.000 Y1.795 F9000", 1)
    text = text.replace("G0 X20.000 Y0.575 F9000", "G0 X20.000 Y4.425 F9000", 1)
    open(dst, "w").write(text)


def _poke_outward(src, dst):
    """Push one plantar endpoint 0.3 mm below the outer edge (Y centre 0.645 -> 0.345, edge was 0)."""
    text = open(src).read()
    text = text.replace("G1 X220.000 Y0.645 E", "G1 X220.000 Y0.345 E", 1)
    open(dst, "w").write(text)


